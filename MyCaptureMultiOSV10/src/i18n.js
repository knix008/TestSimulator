let language = 'ko';

/** `ko` for Korean systems, English everywhere else. */
export function systemLanguage(locale = globalThis.navigator?.language ?? 'ko') {
  return String(locale).toLowerCase().startsWith('ko') ? 'ko' : 'en';
}

export function setLanguage(value) {
  language = LANGUAGES.includes(value) ? value : systemLanguage();
  if (globalThis.document) document.documentElement.lang = language;
  return language;
}

export const getLanguage = () => language;

export function t(key, values = {}) {
  const text = messages[language]?.[key] ?? messages.ko[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in values ? String(values[name]) : match));
}
