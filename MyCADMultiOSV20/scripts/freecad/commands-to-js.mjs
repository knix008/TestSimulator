// Turns the command list FreeCAD's GUI reports (scripts/freecad/list_commands.py)
// into src/domain/freecad-commands.js: every FreeCAD command, by workbench,
// with its English menu text. The coverage map (freecad-map.js) must name a
// MyCAD equivalent for each of them.
//   freecad.exe scripts/freecad/list_commands.py   (MYCAD_FC_OUT=commands.json)
//   node scripts/freecad/commands-to-js.mjs commands.json
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const input = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const all = Object.values(input.workbenches).flatMap((wb) => wb.commands);
const unique = [...new Map(all.map((c) => [c.name, c])).values()];

// The workbench a command belongs to, from its prefix.
const WORKBENCH = {
  Std: 'std', Start: 'std', Part: 'part', PartDesign: 'partdesign', Sketcher: 'sketcher', Draft: 'draft',
  Arch: 'bim', BIM: 'bim', IFC: 'bim', TechDraw: 'techdraw', FEM: 'fem', CAM: 'cam', Mesh: 'mesh', MeshPart: 'mesh',
  Assembly: 'assembly', OpenSCAD: 'openscad', Robot: 'robot', Spreadsheet: 'spreadsheet', Reen: 'reverse',
  Points: 'points', Surface: 'surface', Inspection: 'inspection', Material: 'material', Materials: 'material', Test: 'test',
};
const clean = (text) => String(text ?? '').replace(/&(?=\S)/g, '').replace(/\.\.\.$|…$/, '').replace(/\s+/g, ' ').trim();
const groups = {};
for (const command of unique.sort((a, b) => a.name.localeCompare(b.name))) {
  const prefix = command.name.split('_')[0];
  const wb = WORKBENCH[prefix];
  if (!wb) throw new Error(`unknown prefix ${prefix} (${command.name})`);
  (groups[wb] ??= []).push([command.name, clean(command.menu) || command.name]);
}
const body = Object.entries(groups).map(([wb, list]) => `  ${wb}: [\n${list.map(([name, menu]) => `    [${JSON.stringify(name)}, ${JSON.stringify(menu)}],`).join('\n')}\n  ],`).join('\n');
const text = `// Every command FreeCAD ${input.version} registers in its GUI, by workbench, with
// its English menu text. Generated by scripts/freecad/commands-to-js.mjs from
// scripts/freecad/list_commands.py — do not edit by hand.
export const FREECAD_VERSION = ${JSON.stringify(input.version)};

export const FREECAD_COMMANDS = {
${body}
};

/** [{ name, menu, workbench }] */
export const freecadCommandList = () => Object.entries(FREECAD_COMMANDS).flatMap(([workbench, list]) => list.map(([name, menu]) => ({ name, menu, workbench })));
`;
fs.writeFileSync(path.join(root, 'src', 'domain', 'freecad-commands.js'), text);
console.log(`${unique.length} commands in ${Object.keys(groups).length} workbenches → src/domain/freecad-commands.js`);
