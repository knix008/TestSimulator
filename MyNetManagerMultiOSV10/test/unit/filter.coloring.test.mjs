// Default colouring rules, dark variants, matching order and the colorfilters file format.
import test from 'node:test';
import assert from 'node:assert/strict';
import {
  COLORING_RULES, DARK_COLORING_RULES, darkColors, compileRules, matchColor, parseColorfilters, formatColorfilters, rgb16ToHex, hexToRgb16,
} from '../../src/domain/filter/coloring.js';
import { FIELDS, tcpPacket, udpDnsPacket, arpPacket, tunnelPacket, httpGet, n } from './filter.fixtures.mjs';

// Wireshark 4.6's default colorfilters file (C:\Program Files\Wireshark\colorfilters), first lines.
const WS_FILE = `# DO NOT EDIT THIS FILE!  It was created by Wireshark
@Bad TCP@tcp.analysis.flags && !tcp.analysis.window_update && !tcp.analysis.keep_alive && !tcp.analysis.keep_alive_ack@[4718,10030,11796][63479,34695,34695]
@HSRP State Change@hsrp.state != 8 && hsrp.state != 16@[4718,10030,11796][65535,64764,40092]
!@ARP@arp@[64250,61680,55255][4718,10030,11796]
@TCP@tcp@[59345,58980,65535][4718,10030,11796]
`;

test('defaults: Wireshark 4.6 rules, names, order and colours', () => {
  const names = COLORING_RULES.map((r) => r.name);
  assert.deepEqual(names, ['Bad TCP', 'HSRP State Change', 'Spanning Tree Topology  Change', 'OSPF State Change', 'ICMP errors', 'ARP', 'ICMP',
    'TCP RST', 'SCTP ABORT', 'IPv4 TTL low or unexpected', 'IPv6 hop limit low or unexpected', 'Checksum Errors', 'SMB', 'HTTP', 'DCERPC',
    'Routing', 'TCP SYN/FIN', 'TCP', 'UDP', 'Broadcast', 'System Event']);
  const tcp = COLORING_RULES.find((r) => r.name === 'TCP');
  assert.deepEqual([tcp.bg, tcp.fg], ['#e7e5ff', '#12272e']);
  const bad = COLORING_RULES[0];
  assert.deepEqual([bad.bg, bad.fg], ['#12272e', '#f78787']);
  for (const r of COLORING_RULES) { assert.match(r.fg, /^#[0-9a-f]{6}$/); assert.match(r.bg, /^#[0-9a-f]{6}$/); assert.equal(r.enabled, true); }
  // every default filter compiles (unknown protocols such as hsrp are treated as absent)
  for (const c of compileRules(COLORING_RULES, { fields: FIELDS })) assert.equal(c.error, null, `${c.name}: ${c.error}`);
});

test('dark variants keep names/filters and give dark backgrounds with light text', () => {
  const lum = (h) => { const v = [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16)); return (0.2126 * v[0] + 0.7152 * v[1] + 0.0722 * v[2]) / 255; };
  assert.equal(DARK_COLORING_RULES.length, COLORING_RULES.length);
  DARK_COLORING_RULES.forEach((r, i) => {
    assert.equal(r.name, COLORING_RULES[i].name);
    assert.equal(r.filter, COLORING_RULES[i].filter);
    assert.ok(lum(r.bg) < 0.4, `${r.name} bg ${r.bg}`);
    assert.ok(lum(r.fg) - lum(r.bg) > 0.3, `${r.name} contrast ${r.fg} on ${r.bg}`);
  });
  assert.deepEqual(darkColors([{ name: 'x', filter: 'tcp', fg: '#000000', bg: '#ffffff' }])[0].name, 'x');
});

test('matchColor: first matching enabled rule wins', () => {
  const rules = compileRules(COLORING_RULES, { fields: FIELDS });
  const name = (d) => matchColor(rules, d)?.name ?? null;
  assert.equal(name(tcpPacket({ flags: 0x018, dport: 443 })), 'TCP');
  assert.equal(name(tcpPacket({ flags: 0x002, dport: 443 })), 'TCP SYN/FIN');
  assert.equal(name(tcpPacket({ flags: 0x014, dport: 443 })), 'TCP RST');
  assert.equal(name(tcpPacket({ flags: 0x018, dport: 80 })), 'HTTP');
  assert.equal(name(httpGet()), 'HTTP');
  assert.equal(name(tcpPacket({ dport: 443, extraTcp: [n('tcp.analysis.flags', null)] })), 'Bad TCP');
  assert.equal(name(tcpPacket({ dport: 443, ttl: 2 })), 'IPv4 TTL low or unexpected');
  assert.equal(name(udpDnsPacket()), 'UDP');
  assert.equal(name(arpPacket()), 'ARP');
  assert.equal(name(tunnelPacket()), 'ICMP');
  const tcpBad = tcpPacket({ dport: 443, extraTcp: [n('tcp.checksum.status', 0)] });
  assert.equal(name(tcpBad), 'Checksum Errors');
  // disabling a rule falls through to the next
  const noTcp = compileRules(COLORING_RULES.map((r) => (r.name === 'TCP' ? { ...r, enabled: false } : r)), { fields: FIELDS });
  assert.equal(matchColor(noTcp, tcpPacket({ dport: 443 })), null);
  assert.deepEqual(matchColor(rules, arpPacket()), { name: 'ARP', fg: '#12272e', bg: '#faf0d7' });
});

test('a rule whose filter does not compile is kept, reported and never matches', () => {
  const rules = compileRules([{ name: 'broken', filter: 'tcp.port ==', fg: '#000000', bg: '#ffffff' }, { name: 'tcp', filter: 'tcp', fg: '#000000', bg: '#eeeeee' }], { fields: FIELDS });
  assert.match(rules[0].error, /Unexpected end/);
  assert.equal(matchColor(rules, tcpPacket()).name, 'tcp');
});

test('colorfilters file: parse, disabled rules, round trip with exact 16-bit values', () => {
  const { rules, errors } = parseColorfilters(WS_FILE + 'garbage line\n');
  assert.equal(rules.length, 4);
  assert.equal(errors.length, 1);
  assert.equal(rules[2].name, 'ARP');
  assert.equal(rules[2].enabled, false);
  assert.equal(rules[0].bg, '#12272e');
  const out = formatColorfilters(rules);
  assert.deepEqual(out.split('\n').slice(1), WS_FILE.split('\n').slice(1));
  // edited colours are written from the hex value
  const edited = formatColorfilters([{ name: 'Mine', filter: 'udp && ip.ttl < 5', fg: '#ff0000', bg: '#00ff00', enabled: true }]);
  assert.match(edited, /^@Mine@udp && ip\.ttl < 5@\[0,65535,0\]\[65535,0,0\]$/m);
  assert.equal(parseColorfilters(edited).rules[0].bg, '#00ff00');
  assert.equal(rgb16ToHex([65535, 0, 257]), '#ff0001');
  assert.deepEqual(hexToRgb16('#0102ff'), [257, 514, 65535]);
  // the whole default set survives a round trip
  const all = parseColorfilters(formatColorfilters(COLORING_RULES)).rules;
  assert.deepEqual(all, COLORING_RULES.map((r) => ({ ...r })));
});
