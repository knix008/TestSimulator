export const messages = { ko, en } as const

export function translate(locale: Locale, key: MessageKey, ...args: string[]): string {
  const table = messages[locale] ?? messages.ko
  let text = table[key] ?? messages.ko[key] ?? key
  args.forEach((arg, i) => {
    text = text.replace(`{${i}}`, arg)
  })
  return text
}

export const STORAGE_LOCALE = 'isomaker.locale'
export const STORAGE_THEME = 'isomaker.theme'

export function loadLocale(): Locale {
  const v = localStorage.getItem(STORAGE_LOCALE)
  return v === 'en' ? 'en' : 'ko'
}

export function loadTheme(): Theme {
  const v = localStorage.getItem(STORAGE_THEME)
  return v === 'light' ? 'light' : 'dark'
}
