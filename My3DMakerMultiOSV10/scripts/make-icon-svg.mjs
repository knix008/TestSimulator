// Writes assets/icon.svg: the steel spur gear and the small amber gear on the deep steel-blue tile, plus a
// third small teal gear at the upper left that meshes with the steel gear. The two original gears come from
// assets/icon-base.svg; the third gear's outline is computed here (straight flanks, like the others).
// Render all icon files afterwards with `npm run build:icons`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const f = (v) => Number(v.toFixed(1));

/** Gear outline: N teeth, tip radius R, root radius r, straight flanks; a bore of radius b. */
function gear(cx, cy, N, R, r, phase, b = 0) {
  const step = (2 * Math.PI) / N;
  const tip = step * 0.17;
  const rootHalf = step * 0.27;
  const p = (rad, a) => `${f(cx + rad * Math.cos(a))},${f(cy + rad * Math.sin(a))}`;
  const parts = [];
  for (let i = 0; i < N; i++) {
    const a = phase + i * step;
    parts.push(`${i ? 'L' : 'M'}${p(r, a - rootHalf)} L${p(R, a - tip)} A${R} ${R} 0 0 1 ${p(R, a + tip)} L${p(r, a + rootHalf)} A${r} ${r} 0 0 1 ${p(r, a + step - rootHalf)}`);
  }
  const bore = b ? ` M${f(cx - b)} ${f(cy)} a${b} ${b} 0 1 0 ${2 * b} 0 a${b} ${b} 0 1 0 ${-2 * b} 0Z` : '';
  return `${parts.join(' ')} Z${bore}`;
}

// Third gear: 10 teeth, tip 108, root 82, at the upper left. Centre distance to the steel gear (468, 562) is
// 307 — between the root-to-tip sum (196 + 108 = 304) and the pitch sum (~313): the teeth interlock.
const [cx, cy] = [282, 318];
const phase = Math.atan2(562 - cy, 468 - cx) + Math.PI / 10; // a gap faces the steel gear's tooth
const third = `    <g filter="url(#shadow)">
      <path d="${gear(cx + 7, cy + 12, 10, 108, 82, phase)}" fill="url(#tealEdge)"/>
      <path d="${gear(cx, cy, 10, 108, 82, phase, 28)}" fill="url(#teal)" fill-rule="evenodd" stroke="#0b4f52" stroke-width="4"/>
      <path d="M${cx - 54} ${cy} a54 54 0 1 0 108 0 a54 54 0 1 0 -108 0Z" fill="none" stroke="#d8fbf6" stroke-opacity="0.55" stroke-width="6"/>
    </g>
`;
const gradients = `    <linearGradient id="teal" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#b6f5ea"/>
      <stop offset="0.5" stop-color="#2fbfab"/>
      <stop offset="1" stop-color="#127a70"/>
    </linearGradient>
    <linearGradient id="tealEdge" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#127a70"/>
      <stop offset="1" stop-color="#06403b"/>
    </linearGradient>
`;
let svg = fs.readFileSync(path.join(root, 'assets', 'icon-base.svg'), 'utf8');
svg = svg.replace(/<!--[\s\S]*?-->/, `<!-- My3DMaker app icon: a machined steel spur gear meshing with a small amber gear and a small teal gear, on a
       deep steel-blue tile lit from the upper left. Generated by scripts/make-icon-svg.mjs from assets/icon-base.svg. -->`);
svg = svg.replace('    <clipPath id="tileClip">', `${gradients}    <clipPath id="tileClip">`);
// Under the steel gear (drawn before it), so the steel teeth lie over the teal ones where they meet.
const steelAt = svg.lastIndexOf('    <g filter="url(#shadow)">');
svg = `${svg.slice(0, steelAt)}${third}${svg.slice(steelAt)}`;
fs.writeFileSync(path.join(root, 'assets', 'icon.svg'), svg);
console.log('assets/icon.svg: three gears');
