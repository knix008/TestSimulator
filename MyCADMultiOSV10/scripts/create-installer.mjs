// Generates the NSIS include that lets the user pick which supported file
// types the installer registers with Windows, plus a JSON copy of the table so
// the application and the installer can be checked against each other.
//
//   npm run build:installer
//
// The table mirrors FILE_TYPES in src/core/fileTypes.ts; tests/filetypes.test.ts
// fails if the two ever drift apart.
