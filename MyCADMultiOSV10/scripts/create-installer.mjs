// Generates the NSIS include that lets the user pick which supported file
// types the installer registers with Windows, plus a JSON copy of the table so
// the application and the installer can be checked against each other.
//
//   npm run build:installer
//
// The table mirrors FILE_TYPES in src/core/fileTypes.ts; tests/filetypes.test.ts
// fails if the two ever drift apart.
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')

export const FILE_TYPES = [
  { ext: 'mycad', name: 'MyCAD.Document', ko: 'MyCAD 3D 문서', en: 'MyCAD 3D document', role: 'Editor', default: true, builtin: true },
  { ext: 'stl', name: 'MyCAD.Stl', ko: 'STL 메쉬', en: 'STL mesh', role: 'Viewer', default: true },
  { ext: 'obj', name: 'MyCAD.Obj', ko: 'OBJ 메쉬', en: 'OBJ mesh', role: 'Viewer', default: true },
  { ext: 'dxf', name: 'MyCAD.Dxf', ko: 'DXF 도면', en: 'DXF drawing', role: 'Viewer', default: true },
  { ext: 'svg', name: 'MyCAD.Svg', ko: 'SVG 도면', en: 'SVG drawing', role: 'Viewer', default: false },
  { ext: 'scad', name: 'MyCAD.OpenScad', ko: 'OpenSCAD 소스', en: 'OpenSCAD source', role: 'Viewer', default: true },
  { ext: 'ifc', name: 'MyCAD.Ifc', ko: 'IFC 건축 모델', en: 'IFC building model', role: 'Viewer', default: true },
  { ext: 'asc', name: 'MyCAD.Points', ko: '점군 (ASC)', en: 'Point cloud (ASC)', role: 'Viewer', default: false },
  { ext: 'xyz', name: 'MyCAD.PointsXyz', ko: '점군 (XYZ)', en: 'Point cloud (XYZ)', role: 'Viewer', default: false },
  { ext: 'nc', name: 'MyCAD.Gcode', ko: 'G코드 가공 경로', en: 'G-code toolpath', role: 'Viewer', default: false },
  { ext: 'gcode', name: 'MyCAD.GcodeAlt', ko: 'G코드 가공 경로', en: 'G-code toolpath', role: 'Viewer', default: false },
  { ext: 'mycadmacro', name: 'MyCAD.Macro', ko: 'MyCAD 매크로', en: 'MyCAD macro', role: 'Editor', default: true },
  { ext: 'mycadaddon', name: 'MyCAD.Addon', ko: 'MyCAD 애드온', en: 'MyCAD addon', role: 'Editor', default: true }
]

/** .mycad is the application's own document type and is always registered. */
const CHOOSABLE = FILE_TYPES.filter((type) => !type.builtin)

const COLUMN_WIDTH = 210
const ROW_HEIGHT = 15

function nsh() {
  const lines = []
  lines.push('; Generated by scripts/create-installer.mjs - do not edit by hand.')
  lines.push('!include "LogicLib.nsh"')
  lines.push('!include "nsDialogs.nsh"')
  lines.push('')
  lines.push(`!define MYCAD_ASSOC_COUNT ${CHOOSABLE.length}`)
  // Only the installer has the wizard page; declaring these in the uninstaller
  // pass as well would make makensis warn about unused variables, and
  // electron-builder turns NSIS warnings into errors.
  lines.push('!ifndef BUILD_UNINSTALLER')
  lines.push('Var AssocDialog')
  lines.push('Var AssocAllButton')
  lines.push('Var AssocNoneButton')
  CHOOSABLE.forEach((type, index) => {
    lines.push(`Var AssocBox${index}`)
    lines.push(`Var AssocState${index}`)
  })
  lines.push('!endif')
  lines.push('')

  // Default states, applied before the page is shown.
  lines.push('!macro MyCadAssocDefaults')
  CHOOSABLE.forEach((type, index) => {
    lines.push(`  StrCpy $AssocState${index} "${type.default ? '1' : '0'}"`)
  })
  lines.push('!macroend')
  lines.push('')

  // The page itself.
  lines.push('!macro MyCadAssocPageCreate')
  lines.push('  nsDialogs::Create 1018')
  lines.push('  Pop $AssocDialog')
  lines.push('  ${If} $AssocDialog == error')
  lines.push('    Abort')
  lines.push('  ${EndIf}')
  // MUI2 is only loaded for the installer pass; the uninstaller compiles the
  // same file without it, so the header text is set only when it exists.
  lines.push('  !ifmacrodef MUI_HEADER_TEXT')
  lines.push('  ${If} $LANGUAGE == 1042')
  lines.push('    !insertmacro MUI_HEADER_TEXT "파일 형식 연결" "MyCAD로 열 파일 형식을 선택하세요."')
  lines.push('  ${Else}')
  lines.push('    !insertmacro MUI_HEADER_TEXT "File associations" "Choose which file types open with MyCAD."')
  lines.push('  ${EndIf}')
  lines.push('  !endif')
  CHOOSABLE.forEach((type, index) => {
    const column = index < Math.ceil(CHOOSABLE.length / 2) ? 0 : 1
    const row = index < Math.ceil(CHOOSABLE.length / 2) ? index : index - Math.ceil(CHOOSABLE.length / 2)
    const x = column * COLUMN_WIDTH
    const y = row * ROW_HEIGHT
    lines.push(`  ${'${NSD_CreateCheckbox}'} ${x}u ${y}u ${COLUMN_WIDTH - 10}u 12u ""`)
    lines.push(`  Pop $AssocBox${index}`)
    lines.push('  ${If} $LANGUAGE == 1042')
    lines.push(`    ${'${NSD_SetText}'} $AssocBox${index} ".${type.ext} — ${type.ko}"`)
    lines.push('  ${Else}')
    lines.push(`    ${'${NSD_SetText}'} $AssocBox${index} ".${type.ext} — ${type.en}"`)
    lines.push('  ${EndIf}')
    lines.push(`  ${'${If}'} $AssocState${index} == "1"`)
    lines.push(`    ${'${NSD_Check}'} $AssocBox${index}`)
    lines.push('  ${EndIf}')
  })
  const buttonRow = Math.ceil(CHOOSABLE.length / 2) * ROW_HEIGHT + 4
  lines.push(`  ${'${NSD_CreateButton}'} 0u ${buttonRow}u 80u 14u ""`)
  lines.push('  Pop $AssocAllButton')
  lines.push(`  ${'${NSD_CreateButton}'} 86u ${buttonRow}u 80u 14u ""`)
  lines.push('  Pop $AssocNoneButton')
  lines.push('  ${If} $LANGUAGE == 1042')
  lines.push(`    ${'${NSD_SetText}'} $AssocAllButton "전체 선택"`)
  lines.push(`    ${'${NSD_SetText}'} $AssocNoneButton "전체 해제"`)
  lines.push('  ${Else}')
  lines.push(`    ${'${NSD_SetText}'} $AssocAllButton "Select all"`)
  lines.push(`    ${'${NSD_SetText}'} $AssocNoneButton "Clear all"`)
  lines.push('  ${EndIf}')
  lines.push(`  ${'${NSD_OnClick}'} $AssocAllButton MyCadAssocSelectAll`)
  lines.push(`  ${'${NSD_OnClick}'} $AssocNoneButton MyCadAssocSelectNone`)
  lines.push('  nsDialogs::Show')
  lines.push('!macroend')
  lines.push('')

  // Tick or clear every box at once, from the two buttons on the page.
  lines.push('!macro MyCadAssocCheckAll')
  CHOOSABLE.forEach((type, index) => {
    lines.push(`  ${'${NSD_Check}'} $AssocBox${index}`)
  })
  lines.push('!macroend')
  lines.push('')
  lines.push('!macro MyCadAssocUncheckAll')
  CHOOSABLE.forEach((type, index) => {
    lines.push(`  ${'${NSD_Uncheck}'} $AssocBox${index}`)
  })
  lines.push('!macroend')
  lines.push('')

  // Read the checkboxes back when the page is left.
  lines.push('!macro MyCadAssocPageLeave')
  CHOOSABLE.forEach((type, index) => {
    lines.push(`  ${'${NSD_GetState}'} $AssocBox${index} $AssocState${index}`)
  })
  lines.push('!macroend')
  lines.push('')

  // Registry writes for the checked types.
  lines.push('!macro MyCadWriteAssociations')
  CHOOSABLE.forEach((type, index) => {
    const progId = type.name
    lines.push(`  ${'${If}'} $AssocState${index} != "0"`)
    lines.push(`    WriteRegStr SHCTX "Software\\Classes\\${progId}" "" "${type.en}"`)
    lines.push(`    WriteRegStr SHCTX "Software\\Classes\\${progId}\\DefaultIcon" "" "$INSTDIR\\resources\\file-icon.ico"`)
    lines.push(`    WriteRegStr SHCTX "Software\\Classes\\${progId}\\shell\\open\\command" "" '"$INSTDIR\\${'${APP_EXECUTABLE_FILENAME}'}" "%1"'`)
    lines.push(`    WriteRegStr SHCTX "Software\\Classes\\.${type.ext}\\OpenWithProgids" "${progId}" ""`)
    if (type.role === 'Editor') {
      lines.push(`    WriteRegStr SHCTX "Software\\Classes\\.${type.ext}" "" "${progId}"`)
    }
    lines.push('  ${EndIf}')
  })
  lines.push('  System::Call \'shell32::SHChangeNotify(i 0x08000000, i 0, i 0, i 0)\'')
  lines.push('!macroend')
  lines.push('')

  // Remove every association we may have written.
  lines.push('!macro MyCadDeleteAssociations')
  CHOOSABLE.forEach((type) => {
    lines.push(`  DeleteRegKey SHCTX "Software\\Classes\\${type.name}"`)
    lines.push(`  DeleteRegValue SHCTX "Software\\Classes\\.${type.ext}\\OpenWithProgids" "${type.name}"`)
    lines.push(`  ReadRegStr $0 SHCTX "Software\\Classes\\.${type.ext}" ""`)
    lines.push(`  ${'${If}'} $0 == "${type.name}"`)
    lines.push(`    DeleteRegValue SHCTX "Software\\Classes\\.${type.ext}" ""`)
    lines.push('  ${EndIf}')
  })
  lines.push('  System::Call \'shell32::SHChangeNotify(i 0x08000000, i 0, i 0, i 0)\'')
  lines.push('!macroend')
  lines.push('')
  return lines.join('\n')
}

mkdirSync(join(root, 'build'), { recursive: true })
writeFileSync(join(root, 'build', 'installer-associations.nsh'), `${nsh()}\n`, 'utf8')
writeFileSync(
  join(root, 'build', 'file-types.json'),
  `${JSON.stringify({ generator: 'scripts/create-installer.mjs', types: FILE_TYPES }, null, 2)}\n`,
  'utf8'
)
console.log(`installer associations written: ${CHOOSABLE.length} selectable + 1 built-in file types`)
