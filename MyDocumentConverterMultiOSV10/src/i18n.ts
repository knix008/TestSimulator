export function t(language: Language, key: string, params?: Record<string, string | number>): string {
  const entry = strings[key]
  let text = entry ? entry[language] : key
  if (params) {
    for (const [name, value] of Object.entries(params)) text = text.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value))
  }
  return text
}

export function hasString(key: string) {
  return key in strings
}

export function formatBytes(size: number): string {
  if (size < 1024) return `${size} B`
  if (size < 1024 * 1024) return `${(size / 1024).toFixed(1)} KB`
  return `${(size / (1024 * 1024)).toFixed(2)} MB`
}
