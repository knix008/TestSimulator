//! YouTube sign-in for videos yt-dlp can't fetch anonymously (age gate, bot check).
//! A window opens youtube.com; once Google's session cookies appear they are written as a
//! Netscape cookies.txt for yt-dlp and kept in the data folder for later downloads.
//! (The Electron build read them from a session partition instead.)

use std::collections::HashSet;
use std::path::{Path, PathBuf};
use std::time::Duration;
use tauri::{AppHandle, Manager, WebviewUrl, WebviewWindowBuilder};

pub const WINDOW: &str = "yt-auth";
const AUTH_NAMES: [&str; 5] = ["LOGIN_INFO", "SAPISID", "__Secure-1PSID", "__Secure-3PSID", "SID"];
const COOKIE_URLS: [&str; 3] = ["https://www.youtube.com/", "https://accounts.google.com/", "https://www.google.com/"];

pub struct Saved {
  pub path: PathBuf,
  pub authenticated: bool,
}

fn file(data_dir: &Path) -> PathBuf {
  data_dir.join("youtube-cookies.txt")
}

fn has_auth<'a>(names: impl IntoIterator<Item = &'a str>) -> bool {
  names.into_iter().any(|n| AUTH_NAMES.contains(&n))
}

/// The cookies.txt from an earlier sign-in, if any.
pub fn saved(data_dir: &Path) -> Option<Saved> {
  let path = file(data_dir);
  let text = std::fs::read_to_string(&path).ok()?;
  let names: Vec<&str> = text
    .lines()
    .filter(|l| !l.starts_with('#'))
    .filter_map(|l| l.split('\t').nth(5))
    .collect();
  if names.is_empty() {
    return None;
  }
  let authenticated = has_auth(names.iter().copied());
  Some(Saved { path, authenticated })
}

struct Row {
  domain: String,
  path: String,
  secure: bool,
  expires: i64,
  name: String,
  value: String,
}

fn collect(app: &AppHandle) -> Vec<Row> {
  let Some(win) = app.get_webview_window(WINDOW) else { return Vec::new() };
  let mut seen = HashSet::new();
  let mut rows = Vec::new();
  for url in COOKIE_URLS {
    let Ok(url) = url.parse() else { continue };
    let Ok(list) = win.cookies_for_url(url) else { continue };
    for c in list {
      let domain = c.domain().unwrap_or("").to_string();
      let path = c.path().unwrap_or("/").to_string();
      if !seen.insert(format!("{domain}|{}|{path}", c.name())) {
        continue;
      }
      rows.push(Row {
        domain,
        path,
        secure: c.secure().unwrap_or(false),
        expires: c.expires_datetime().map(|t| t.unix_timestamp()).unwrap_or(0),
        name: c.name().to_string(),
        value: c.value().to_string(),
      });
    }
  }
  rows
}

fn netscape(rows: &[Row]) -> String {
  let mut out = String::from("# Netscape HTTP Cookie File\n# Generated by MyVideoPlayer\n");
  for r in rows {
    let domain = if r.domain.is_empty() || r.domain.starts_with('.') { r.domain.clone() } else { format!(".{}", r.domain) };
    out.push_str(&format!(
      "{domain}\tTRUE\t{}\t{}\t{}\t{}\t{}\n",
      r.path,
      if r.secure { "TRUE" } else { "FALSE" },
      r.expires.max(0),
      r.name,
      r.value
    ));
  }
  out
}

fn write(data_dir: &Path, rows: &[Row]) -> Option<Saved> {
  if rows.is_empty() {
    return saved(data_dir);
  }
  let _ = std::fs::create_dir_all(data_dir);
  let path = file(data_dir);
  std::fs::write(&path, netscape(rows)).ok()?;
  Some(Saved { path, authenticated: has_auth(rows.iter().map(|r| r.name.as_str())) })
}

/// Opens the sign-in window and waits until Google's session cookies show up (or the user
/// closes the window). Must run off the main thread.
pub fn prompt(app: &AppHandle, data_dir: &Path) -> Option<Saved> {
  if app.get_webview_window(WINDOW).is_none() {
    let mut builder = WebviewWindowBuilder::new(app, WINDOW, WebviewUrl::External("https://www.youtube.com/".parse().ok()?))
      .title("Sign in to YouTube")
      .inner_size(980.0, 740.0)
      .center();
    if let Some(main) = app.get_webview_window("main") {
      builder = builder.parent(&main).ok()?;
    }
    builder.build().ok()?;
  }
  let mut last = Vec::new();
  loop {
    std::thread::sleep(Duration::from_millis(1200));
    if app.get_webview_window(WINDOW).is_none() {
      break;
    }
    last = collect(app);
    if has_auth(last.iter().map(|r| r.name.as_str())) {
      // Give the session a moment to settle the remaining cookies.
      std::thread::sleep(Duration::from_millis(800));
      let more = collect(app);
      if !more.is_empty() {
        last = more;
      }
      if let Some(w) = app.get_webview_window(WINDOW) {
        let _ = w.close();
      }
      break;
    }
  }
  write(data_dir, &last)
}

#[cfg(test)]
mod tests {
  use super::*;

  #[test]
  fn writes_and_reads_cookies_txt() {
    let dir = tempfile::tempdir().unwrap();
    let rows = vec![
      Row { domain: "youtube.com".into(), path: "/".into(), secure: true, expires: 1900000000, name: "SAPISID".into(), value: "x".into() },
      Row { domain: ".google.com".into(), path: "/".into(), secure: false, expires: -1, name: "NID".into(), value: "y".into() },
    ];
    let s = write(dir.path(), &rows).unwrap();
    assert!(s.authenticated);
    let text = std::fs::read_to_string(&s.path).unwrap();
    assert!(text.contains(".youtube.com\tTRUE\t/\tTRUE\t1900000000\tSAPISID\tx"));
    assert!(text.contains(".google.com\tTRUE\t/\tFALSE\t0\tNID\ty"));
    assert!(saved(dir.path()).unwrap().authenticated);
  }
}
