let currentLocale = 'en';

export const SUPPORTED_LOCALES = [
  { id: 'en', labelKey: 'langEnglish' },
  { id: 'ko', labelKey: 'langKorean' }
];

export function detectLocale() {
  const lang = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
  return lang.startsWith('ko') ? 'ko' : 'en';
}

export function getLocale() {
  return currentLocale;
}

export function setLocale(locale) {
  currentLocale = locale === 'ko' ? 'ko' : 'en';
  if (typeof document !== 'undefined') {
    document.documentElement.lang = currentLocale;
  }
  return currentLocale;
}

export function t(key, vars = {}) {
  const dict = dictionaries[currentLocale] || dictionaries.en;
  let text = dict[key] ?? dictionaries.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    text = text.replaceAll(`{${k}}`, String(v));
  }
  return text;
}

export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (!key) return;
    const value = t(key);
    if (el.tagName === 'TITLE') el.textContent = value;
    else if (el.children.length && el.dataset.i18nKeepHtml === '1') {
      /* keep structure */
    } else {
      el.textContent = value;
    }
  });

  root.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const key = el.getAttribute('data-i18n-html');
    if (!key) return;
    el.innerHTML = t(key).replaceAll('\n', '<br />');
  });

  root.querySelectorAll('[data-i18n-tooltip]').forEach((el) => {
    const key = el.getAttribute('data-i18n-tooltip');
    if (key) el.setAttribute('data-tooltip', t(key));
  });

  root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    const key = el.getAttribute('data-i18n-aria');
    if (key) el.setAttribute('aria-label', t(key));
  });

  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) el.setAttribute('placeholder', t(key));
  });

  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const key = el.getAttribute('data-i18n-title');
    if (key) el.setAttribute('title', t(key));
  });
}

export function resolveInitialLocale(saved) {
  if (saved === 'en' || saved === 'ko') return saved;
  return detectLocale() || STORAGE_LOCALE_FALLBACK;
}
