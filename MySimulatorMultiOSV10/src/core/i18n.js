export const MESSAGES = { ko, en };

let current = 'ko';

export function setLanguage(language) {
  current = language === 'en' ? 'en' : 'ko';
  globalThis.document?.documentElement?.setAttribute('lang', current);
}

export function getLanguage() {
  return current;
}

export function t(key, args) {
  let text = MESSAGES[current][key] ?? MESSAGES.ko[key] ?? key;
  if (args) for (const [name, value] of Object.entries(args)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}
