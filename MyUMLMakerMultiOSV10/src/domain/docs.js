const h = (text) => String(text ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const anchor = (id) => `e-${String(id).replace(/[^\w-]/g, (c) => `_${c.charCodeAt(0).toString(16)}`)}`;
/** The documented element nearest to e (itself or an owner): a feature links to its classifier. */
const sectionOf = (e, index, shownIds) => { for (let x = e; x; x = index.parent(x._id)) if (shownIds.has(x._id)) return x._id; return null; };
const linker = (index, shownIds) => (element, language) => {
  if (!element) return '';
  const text = h(element.name || `(${typeLabel(element._type, language)})`);
  const id = sectionOf(element, index, shownIds);
  return id ? `<a href="#${anchor(id)}">${text}</a>` : text;
};

