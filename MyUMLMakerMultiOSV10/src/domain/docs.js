function table(head, rows) {
  if (!rows.length) return '';
  return `<table><thead><tr>${head.map((c) => `<th>${h(c)}</th>`).join('')}</tr></thead><tbody>${rows.map((r) => `<tr>${r.map((c) => `<td>${c}</td>`).join('')}</tr>`).join('')}</tbody></table>`;
}

/**
 * One self-contained HTML file documenting the project.
 * renderDiagram(diagram) → '<svg …>' (optional; a failing or missing callback leaves the picture out).
 */
export function htmlDocs(project, { language = 'ko', renderDiagram = null } = {}) {
  const t = TEXT[language] ?? TEXT.en;
  const index = buildIndex(project);
  const { diagramsOf, relationshipsOf } = crossReferences(project);
  const items = documented(project);
  const shownIds = new Set(items.map((i) => i.element._id));
  const link = linker(index, shownIds);
  // Navigation tree.
  const navOf = (element) => {
    const kids = childrenOf(element, { ends: false }).filter((c) => shownIds.has(c._id));
    const own = element === project ? '' : `<a href="#${anchor(element._id)}">${h(element.name || `(${typeLabel(element._type, language)})`)}</a><span class="t">${h(typeLabel(element._type, language))}</span>`;
    const sub = kids.length ? `<ul>${kids.map((k) => `<li>${navOf(k)}</li>`).join('')}</ul>` : '';
    return own + sub;
  };
  const sections = items.map(({ element }) => {
    const f = facts(project, element, index, language, diagramsOf, relationshipsOf);
    const parts = [`<section id="${anchor(element._id)}">`, `<h2>${h(element.name || `(${typeLabel(element._type, language)})`)}</h2>`,
      `<div class="meta">${h(t.type)}: ${h(typeLabel(element._type, language))} · ${h(t.qualifiedName)}: <code>${h(qualifiedName(project, element._id, index))}</code></div>`];
    if (element.documentation) parts.push(`<h3>${h(t.documentation)}</h3><div class="doc">${h(element.documentation)}</div>`);
    if (f.properties.length) parts.push(`<h3>${h(t.properties)}</h3>${table([t.property, t.value], f.properties.map(([k, v, id]) => [h(k), id && index.get(id) ? link(index.get(id), language) : h(v)]))}`);
    if (f.literals.length) parts.push(`<h3>${h(t.literals)}</h3><p>${f.literals.map((l) => `<code>${h(l)}</code>`).join(' ')}</p>`);
    if (f.attributes.length) parts.push(`<h3>${h(t.attributes)}</h3>${table([t.visibility, t.name, t.typeCol, t.multiplicity, t.defaultValue], f.attributes.map(([v, n, ty, m, d, st]) => [h(v), st ? `<u>${h(n)}</u>` : h(n), h(ty), h(m), h(d)]))}`);
    if (f.operations.length) parts.push(`<h3>${h(t.operations)}</h3>${table([t.visibility, t.name, t.parameters, t.returns], f.operations.map(([v, n, p, r, st, ab]) => [h(v), `${st ? '<u>' : ''}${ab ? '<i>' : ''}${h(n)}${ab ? '</i>' : ''}${st ? '</u>' : ''}`, h(p), h(r)]))}`);
    if (f.columns.length) parts.push(`<h3>${h(t.columns)}</h3>${table([t.name, t.typeCol, t.key, 'NULL', fieldLabel('referenceTo', language)], f.columns.map((r) => r.map(h)))}`);
    if (f.relationships.length) parts.push(`<h3>${h(t.relationships)}</h3><ul>${f.relationships.map((r) => `<li>${link(r.relation, language)} — ${h(r.type)}: ${link(r.from, language)} → ${link(r.to, language)}</li>`).join('')}</ul>`);
    if (f.diagrams.length) parts.push(`<h3>${h(t.appearsIn)}</h3><ul>${f.diagrams.map((d) => `<li>${link(d, language)}</li>`).join('')}</ul>`);
    if (isDiagram(element)) {
      let svg = '';
      if (typeof renderDiagram === 'function') { try { svg = String(renderDiagram(element) ?? ''); } catch { svg = ''; } }
      parts.push(`<div class="svg">${svg || h(t.noDiagram)}</div>`);
      const shown = [...new Set((element.ownedViews ?? []).map((v) => refId(v.model)).filter(Boolean))].map((id) => index.get(id)).filter((e) => e && shownIds.has(e._id));
      if (shown.length) parts.push(`<h3>${h(t.shows)}</h3><p>${shown.map((e) => link(e, language)).join(', ')}</p>`);
    }
    parts.push('</section>');
    return parts.join('\n');
  });
  const info = ['author', 'company', 'version', 'copyright'].filter((k) => project[k]).map((k) => `${h(fieldLabel(k, language))}: ${h(project[k])}`).join(' · ');
  return `<!doctype html>
<html lang="${language === 'ko' ? 'ko' : 'en'}">
<head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>${h(project.name || t.project)}</title>
<style>${CSS}</style></head>
<body>
<nav><input id="q" type="search" placeholder="${h(t.search)}" aria-label="${h(t.search)}"><strong>${h(t.contents)}</strong><ul>${childrenOf(project, { ends: false }).filter((c) => shownIds.has(c._id)).map((c) => `<li>${navOf(c)}</li>`).join('')}</ul></nav>
<main>
<header><h1>${h(project.name || t.project)}</h1>${info ? `<div class="meta">${info}</div>` : ''}${project.documentation ? `<div class="doc">${h(project.documentation)}</div>` : ''}</header>
${sections.join('\n')}
<footer class="meta">${h(t.generated)}</footer>
</main>
<script>${SCRIPT}</script>
</body>
</html>
`;
}

// ───────────────────────── Markdown

const md = (text) => String(text ?? '').replace(/([\\`*_[\]|<>])/g, '\\$1').replace(/\r?\n/g, ' ');
function mdTable(head, rows) {
  if (!rows.length) return '';
  return `| ${head.map(md).join(' | ')} |\n| ${head.map(() => '---').join(' | ')} |\n${rows.map((r) => `| ${r.join(' | ')} |`).join('\n')}\n`;
}

/**
 * One Markdown document. imageLink(diagram) → URL or path of the diagram's
 * image (optional; without it diagrams get no picture).
 */
export function markdownDocs(project, { language = 'ko', imageLink = null } = {}) {
  const t = TEXT[language] ?? TEXT.en;
  const index = buildIndex(project);
  const { diagramsOf, relationshipsOf } = crossReferences(project);
  const items = documented(project);
  const depth = new Map([[project._id, 0]]);
  for (const { element, parent } of items) depth.set(element._id, (depth.get(parent?._id) ?? 0) + 1);
  const name = (e) => e?.name || `(${typeLabel(e?._type ?? '', language)})`;
  const shownIds = new Set(items.map((i) => i.element._id));
  const ref = (e) => { const id = e ? sectionOf(e, index, shownIds) : null; return e ? (id ? `[${md(name(e))}](#${anchor(id)})` : md(name(e))) : ''; };
  const out = [`# ${md(project.name || t.project)}`, ''];
  const info = ['author', 'company', 'version', 'copyright'].filter((k) => project[k]).map((k) => `${fieldLabel(k, language)}: ${md(project[k])}`);
  if (info.length) out.push(info.join(' · '), '');
  if (project.documentation) out.push(project.documentation, '');
  out.push(`## ${t.contents}`, '');
  for (const { element } of items) out.push(`${'  '.repeat(Math.max(0, depth.get(element._id) - 1))}- ${ref(element)} — ${typeLabel(element._type, language)}`);
  out.push('');
  for (const { element } of items) {
    const f = facts(project, element, index, language, diagramsOf, relationshipsOf);
    out.push(`<a id="${anchor(element._id)}"></a>`, '', `${'#'.repeat(Math.min(6, 1 + depth.get(element._id)))} ${md(name(element))}`, '');
    out.push(`- ${t.type}: ${typeLabel(element._type, language)}`, `- ${t.qualifiedName}: \`${qualifiedName(project, element._id, index)}\``, '');
    if (element.documentation) out.push(element.documentation, '');
    if (f.properties.length) out.push(`**${t.properties}**`, '', mdTable([t.property, t.value], f.properties.map(([k, v, id]) => [md(k), id && index.get(id) ? ref(index.get(id)) : md(v)])));
    if (f.literals.length) out.push(`**${t.literals}**: ${f.literals.map((l) => `\`${l}\``).join(', ')}`, '');
    if (f.attributes.length) out.push(`**${t.attributes}**`, '', mdTable([t.visibility, t.name, t.typeCol, t.multiplicity, t.defaultValue], f.attributes.map(([v, n, ty, m, d]) => [md(v), md(n), md(ty), md(m), md(d)])));
    if (f.operations.length) out.push(`**${t.operations}**`, '', mdTable([t.visibility, t.name, t.parameters, t.returns], f.operations.map(([v, n, p, r]) => [md(v), md(n), md(p), md(r)])));
    if (f.columns.length) out.push(`**${t.columns}**`, '', mdTable([t.name, t.typeCol, t.key, 'NULL', fieldLabel('referenceTo', language)], f.columns.map((r) => r.map(md))));
    if (f.relationships.length) out.push(`**${t.relationships}**`, '', ...f.relationships.map((r) => `- ${r.type}${r.name ? ` ${md(r.name)}` : ''}: ${ref(r.from)} → ${ref(r.to)}`), '');
    if (f.diagrams.length) out.push(`**${t.appearsIn}**: ${f.diagrams.map(ref).join(', ')}`, '');
    if (isDiagram(element) && typeof imageLink === 'function') {
      let url = '';
      try { url = String(imageLink(element) ?? ''); } catch { url = ''; }
      if (url) out.push(`![${md(name(element))}](${url.replace(/ /g, '%20').replace(/\)/g, '%29')})`, '');
    }
  }
  out.push('---', `*${t.generated}*`, '');
  return out.join('\n');
}
