/** Elements that get their own section: everything but features, ends, tags and views. */
function documented(project) {
  const out = [];
  walk(project, (element, parent) => {
    if (element === project) return;
    const def = typeDef(element._type);
    if (!def || def.feature || /End$/.test(element._type) || element._type === 'UMLTag' || element._type === 'UMLRegion' && !element.name) return;
    out.push({ element, parent });
  });
  return out;
}

const humanize = (key) => key.replace(/^is([A-Z])/, '$1').replace(/([a-z])([A-Z])/g, '$1 $2').replace(/^./, (c) => c.toUpperCase());
const fieldLabel = (key, language) => (language === 'ko' ? FIELD_KO[key] ?? humanize(key) : humanize(key));
const VIS = { public: '+', private: '-', protected: '#', package: '~' };

/** A field value as plain text (refs → names). */
function valueText(value, index, t) {
  if (value === undefined || value === null || value === '') return '';
  if (typeof value === 'boolean') return value ? t.yes : t.no;
  if (Array.isArray(value)) return value.map((v) => valueText(v, index, t)).filter(Boolean).join(', ');
  if (typeof value === 'object') { if (value.$ref) return index.get(value.$ref)?.name || `(${typeLabel(index.get(value.$ref)?._type ?? '', 'en')})`; return ''; }
  return String(value);
}
const typeOf = (value, index) => (value && typeof value === 'object' ? index.get(value)?.name ?? '' : String(value ?? ''));

/** Rows of an element's facts, shared by both formats: { properties, attributes, operations, literals, columns, relationships, diagrams }. */
function facts(project, element, index, language, diagramsOf, relationshipsOf) {
  const t = TEXT[language] ?? TEXT.en;
  const properties = [];
  const stereo = stereotypeName(element, index);
  if (stereo) properties.push([fieldLabel('stereotype', language), stereo, null]);
  for (const field of fieldsOf(element._type)) {
    if (['name', 'documentation', 'stereotype'].includes(field.key)) continue;
    const raw = element[field.key];
    const text = valueText(raw, index, t);
    if (text === '' || (field.type === 'bool' && raw === false && field.def !== true)) continue;
    properties.push([fieldLabel(field.key, language), text, raw && typeof raw === 'object' && raw.$ref ? raw.$ref : null]);
  }
  if (typeDef(element._type)?.ends === 'association') {
    for (const key of ['end1', 'end2']) {
      const end = element[key];
      if (!end) continue;
      const bits = [index.get(end.reference)?.name, end.name, end.multiplicity, end.cardinality, end.aggregation && end.aggregation !== 'none' ? end.aggregation : '', end.navigable === 'navigable' ? '→' : ''].filter(Boolean);
      properties.push([key, bits.join(' · '), refId(end.reference)]);
    }
  }
  const attributes = (element.attributes ?? []).map((a) => [VIS[a.visibility] ?? '', a.name ?? '', typeOf(a.type, index), a.multiplicity ?? '', a.defaultValue ?? '', a.isStatic]);
  const operations = (element.operations ?? []).map((o) => {
    const params = (o.parameters ?? []).filter((p) => p.direction !== 'return').map((p) => `${p.direction && p.direction !== 'in' ? `${p.direction} ` : ''}${p.name}${typeOf(p.type, index) ? `: ${typeOf(p.type, index)}` : ''}`).join(', ');
    const ret = (o.parameters ?? []).find((p) => p.direction === 'return');
    return [VIS[o.visibility] ?? '', o.name ?? '', params, ret ? typeOf(ret.type, index) : '', o.isStatic, o.isAbstract];
  });
  const literals = (element.literals ?? []).map((l) => l.name);
  const columns = (element.columns ?? []).map((c) => [c.name ?? '', `${c.type ?? ''}${c.length ? `(${c.length})` : ''}`, [c.primaryKey && 'PK', c.foreignKey && 'FK', c.unique && 'UK'].filter(Boolean).join(', '), c.nullable ? t.yes : t.no, valueText(c.referenceTo, index, t)]);
  const relationships = (relationshipsOf.get(element._id) ?? []).map((r) => {
    const [a, b] = relationshipEnds(r);
    return { relation: r, type: typeLabel(r._type, language), name: r.name ?? '', from: index.get(a), to: index.get(b) };
  });
  const diagrams = diagramsOf.get(element._id) ?? [];
  return { properties, attributes, operations, literals, columns, relationships, diagrams };
}

/** element id → diagrams it is shown on; element id → relationships touching it. */
function crossReferences(project) {
  const diagramsOf = new Map();
  const relationshipsOf = new Map();
  walk(project, (element) => {
    if (isDiagram(element)) {
      for (const view of element.ownedViews ?? []) {
        const id = refId(view.model);
        if (!id) continue;
        if (!diagramsOf.has(id)) diagramsOf.set(id, []);
        if (!diagramsOf.get(id).includes(element)) diagramsOf.get(id).push(element);
      }
    }
    if (isRelationship(element)) {
      for (const id of new Set(relationshipEnds(element).filter(Boolean))) {
        if (!relationshipsOf.has(id)) relationshipsOf.set(id, []);
        relationshipsOf.get(id).push(element);
      }
    }
  });
  return { diagramsOf, relationshipsOf };
}

