// Code generation (StarUML's Java, C#, C++, Python, TypeScript, Kotlin, PHP
// and DDL extensions). generateCode() turns every classifier below a model
// element (a class, a package, a whole model …) into source files, one file per
// classifier (two for C++: .h + .cpp), packages becoming folders and
// package / namespace declarations. For 'sql' the ER data models below the
// element become DDL scripts (see sql.js).
//
// The language modules only format text: everything they need to know about
// the model (resolved type names, inherited classes, realized interfaces,
// association ends that become fields, return parameters …) comes from the
// context object built here, so a new language is one small module.
//
// Pure (no DOM, no Node APIs).
import { buildIndex, refId, walk } from '../model.js';
import * as cpp from './cpp.js';
import * as csharp from './csharp.js';
import * as java from './java.js';
import * as kotlin from './kotlin.js';
import * as php from './php.js';
import * as python from './python.js';
import * as sql from './sql.js';
import * as typescript from './typescript.js';

