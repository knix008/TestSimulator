export const SQL_DIALECTS = sql.DIALECTS;

const COMMON = { indentSpaces: 4, useTabs: false, headerComment: true, header: 'Generated by MyUMLMaker', documentation: true };
/** Options per language (the code generation dialog edits a copy). */
export const DEFAULT_CODEGEN_OPTIONS = {
  java: { ...COMMON, getterSetter: false, collection: 'List', todoComments: true },
  csharp: { ...COMMON, getterSetter: false, collection: 'List', todoComments: true },
  cpp: { ...COMMON, collection: 'std::vector', pragmaOnce: false, todoComments: true },
  python: { ...COMMON, typeHints: true, collection: 'list' },
  typescript: { ...COMMON, indentSpaces: 2, collection: 'array', todoComments: true },
  kotlin: { ...COMMON, collection: 'List', todoComments: true },
  php: { ...COMMON, typeHints: true, getterSetter: false, todoComments: true },
  sql: { ...COMMON, indentSpaces: 2, dialect: 'mysql', dropTables: false, quoteIdentifiers: false, foreignKeys: true },
};

const GENERATORS = { java, csharp, cpp, python, typescript, kotlin, php };

/** Classifier types that get a source file. */
export const GENERATED_TYPES = ['UMLClass', 'UMLInterface', 'UMLEnumeration', 'UMLDataType', 'UMLSignal'];
/** Owners that map to a package / namespace / folder. */
const PACKAGE_TYPES = ['UMLPackage', 'UMLSubsystem'];

export function codegenError(code, detail) {
  const error = new Error(code);
  error.code = code;
  error.detail = detail;
  return error;
}

/**
 * Source files for the classifiers (or ER data models for 'sql') below the
 * element `rootId` (the whole project when rootId is empty).
 * Returns [{ path, content }], paths with '/' separators.
 */
export function generateCode(project, rootId, language, options = {}) {
  if (!DEFAULT_CODEGEN_OPTIONS[language]) throw codegenError('codegen.unknownLanguage', language);
  const index = buildIndex(project);
  const root = rootId ? index.get(rootId) : project;
  if (!root) throw codegenError('codegen.noElement', rootId);
  const opts = { ...DEFAULT_CODEGEN_OPTIONS[language], ...options };
  const ctx = makeContext(project, index, language, opts);
  if (language === 'sql') return sql.generate(root, ctx);
  const files = [];
  walk(root, (element) => {
    if (GENERATED_TYPES.includes(element._type)) files.push(...GENERATORS[language].generate(element, ctx));
  });
  return files;
}

