// ───────────────────────── multiplicity

/** Upper bound of a multiplicity ('*' → Infinity, '' → 1). */
export function upperBound(multiplicity) {
  const text = String(multiplicity ?? '').trim();
  if (!text) return 1;
  const upper = text.includes('..') ? text.split('..').pop().trim() : text;
  if (upper === '*' || upper === 'n' || upper === 'N') return Infinity;
  const n = Number(upper);
  return Number.isFinite(n) ? n : 1;
}
export const isMany = (multiplicity) => upperBound(multiplicity) > 1;
export const isOptional = (multiplicity) => /^\s*0\s*\.\.\s*1\s*$/.test(String(multiplicity ?? ''));

// ───────────────────────── the context given to the language modules

function makeContext(project, index, language, options) {
  // Relationships anywhere in the project.
  const generalizations = [];
  const realizations = [];
  const associations = [];
  walk(project, (element) => {
    if (element._type === 'UMLGeneralization') generalizations.push(element);
    else if (element._type === 'UMLInterfaceRealization' || element._type === 'UMLRealization') realizations.push(element);
    else if (element._type === 'UMLAssociation') associations.push(element);
  });

  const unit = options.useTabs ? '\t' : ' '.repeat(Math.max(0, Number(options.indentSpaces) || 0) || 4);
  const resolve = (type) => {
    const id = type && typeof type === 'object' ? refId(type) : null;
    return id ? index.get(id) : null;
  };
  const ident = (name, fallback = 'Unnamed') => {
    const text = String(name ?? '').trim().replace(/[^\p{L}\p{N}_$]+/gu, '_');
    if (!text) return fallback;
    return /^\p{N}/u.test(text) ? `_${text}` : text;
  };
  const typeName = (type) => {
    if (!type) return '';
    if (typeof type === 'object') return ident(resolve(type)?.name ?? '', '');
    const text = String(type).trim();
    const alias = ALIASES[text.toLowerCase()];
    return alias ? PRIMITIVES[alias][language] : text;
  };
  const packagePath = (element) => {
    const out = [];
    for (let owner = index.parent(element._id); owner; owner = index.parent(owner._id)) {
      if (PACKAGE_TYPES.includes(owner._type) && owner.name) out.unshift(ident(owner.name));
    }
    return out;
  };
  const lowerFirst = (text) => (text ? text[0].toLowerCase() + text.slice(1) : text);

  /** Attributes plus navigable association ends (fields), one shape. */
  const fieldsOf = (cls) => {
    const out = (cls.attributes ?? []).map((a) => ({
      name: ident(a.name, 'attr'), type: a.type, multiplicity: a.multiplicity ?? '', visibility: a.visibility ?? 'public',
      isStatic: Boolean(a.isStatic), isReadOnly: Boolean(a.isReadOnly), defaultValue: a.defaultValue ?? '',
      documentation: a.documentation ?? '', association: false, aggregation: a.aggregation ?? 'none', element: a,
    }));
    for (const association of associations) {
      for (const [mine, other] of [[association.end1, association.end2], [association.end2, association.end1]]) {
        if (!mine || !other || refId(mine.reference) !== cls._id) continue;
        if (other.navigable === 'notNavigable') continue;
        if (other.navigable !== 'navigable' && !other.name) continue;
        const target = index.get(other.reference);
        if (!target) continue;
        out.push({
          name: ident(other.name || lowerFirst(target.name), 'ref'), type: { $ref: target._id }, multiplicity: other.multiplicity ?? '',
          visibility: other.visibility ?? 'public', isStatic: false, isReadOnly: Boolean(other.isReadOnly), defaultValue: '',
          documentation: other.documentation ?? '', association: true, aggregation: other.aggregation ?? 'none', element: other,
        });
      }
    }
    return out;
  };

  /** Operations with their parameters split into inputs and the return parameter. */
  const operationsOf = (cls) => (cls.operations ?? []).map((op) => {
    const params = op.parameters ?? [];
    const ret = params.find((p) => p.direction === 'return') ?? null;
    return {
      name: ident(op.name, 'operation'), visibility: op.visibility ?? 'public', isStatic: Boolean(op.isStatic),
      isAbstract: Boolean(op.isAbstract), isLeaf: Boolean(op.isLeaf), documentation: op.documentation ?? '',
      raisedExceptions: String(op.raisedExceptions ?? '').split(',').map((s) => s.trim()).filter(Boolean),
      params: params.filter((p) => p.direction !== 'return').map((p) => ({
        name: ident(p.name, 'arg'), type: p.type, multiplicity: p.multiplicity ?? '', defaultValue: p.defaultValue ?? '', direction: p.direction ?? 'in',
      })),
      returnType: ret ? ret.type : null, returnMultiplicity: ret?.multiplicity ?? '',
      templateParameters: templateParams(op),
      isConstructor: ident(op.name) === ident(cls.name),
      element: op,
    };
  });

  const templateParams = (element) => (element.templateParameters ?? []).map((t) => ({ name: ident(t.name, 'T'), bound: t.parameterType ?? '', defaultValue: t.defaultValue ?? '' }));

  const targetsOf = (list, cls) => list.filter((r) => refId(r.source) === cls._id).map((r) => index.get(r.target)).filter(Boolean);
  const superclasses = (cls) => targetsOf(generalizations, cls);
  const interfaces = (cls) => targetsOf(realizations, cls).filter((t) => t._type === 'UMLInterface');

  /** Classifiers a classifier's code refers to (for imports / includes). */
  const dependencies = (cls) => {
    const out = new Map();
    const add = (element) => { if (element && element._id !== cls._id && GENERATED_TYPES.includes(element._type)) out.set(element._id, element); };
    superclasses(cls).forEach(add);
    interfaces(cls).forEach(add);
    for (const f of fieldsOf(cls)) add(resolve(f.type));
    for (const op of operationsOf(cls)) { add(resolve(op.returnType)); op.params.forEach((p) => add(resolve(p.type))); }
    return [...out.values()];
  };

  /** Header comment lines (with the given line prefix) followed by a blank line, or nothing. */
  const header = (prefix) => (options.headerComment && options.header ? [...String(options.header).split(/\r?\n/).map((l) => `${prefix} ${l}`.trimEnd()), ''] : []);
  /** Documentation text as lines (nothing when documentation output is off). */
  const docLines = (text) => (options.documentation && String(text ?? '').trim() ? String(text).trim().split(/\r?\n/) : []);
  /** A block comment: /** … *\/ style, indented. */
  const docBlock = (text, indent = '') => {
    const lines = docLines(text);
    if (!lines.length) return [];
    return [`${indent}/**`, ...lines.map((l) => `${indent} * ${l}`.trimEnd()), `${indent} */`];
  };

  return {
    project, index, language, options, unit,
    indent: (level) => unit.repeat(level),
    resolve, ident, typeName, packagePath, lowerFirst, fieldsOf, operationsOf, templateParams, superclasses, interfaces,
    dependencies, header, docLines, docBlock, isMany, isOptional, upperBound,
    capitalize: (text) => (text ? text[0].toUpperCase() + text.slice(1) : text),
    join: (lines) => `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`,
    folder: (element) => packagePath(element).map((p) => `${p}/`).join(''),
  };
}
