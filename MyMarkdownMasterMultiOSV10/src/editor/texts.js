export const CALLOUT_TYPES = ['note', 'info', 'tip', 'success', 'question', 'warning', 'failure', 'danger', 'bug', 'example', 'quote', 'abstract', 'todo'];
// Obsidian's aliases for the callout types.
export const CALLOUT_ALIASES = {
  summary: 'abstract', tldr: 'abstract', hint: 'tip', important: 'tip', check: 'success', done: 'success', help: 'question', faq: 'question',
  caution: 'warning', attention: 'warning', fail: 'failure', missing: 'failure', error: 'danger', cite: 'quote',
};
export const calloutType = (raw) => {
  const type = String(raw ?? '').toLowerCase();
  return CALLOUT_TYPES.includes(type) ? type : CALLOUT_ALIASES[type] ?? 'note';
};
export const calloutLabel = (raw) => t(`editor.callout.${calloutType(raw)}`);
