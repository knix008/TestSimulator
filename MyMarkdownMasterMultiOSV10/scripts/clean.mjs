// npm run clean — removes everything a build or test run produces, so the folder holds only what git keeps
// (what is pushed) and the next build starts from scratch.
//
//   npm run clean                 build output (also the Rust core's crates/*/target), installers, generated
//                                 files (public/mdcore.wasm, public/doc/, icon intermediates), test results, caches
//   npm run clean:all             the above + node_modules/ (run `npm install` afterwards); programs still running
//                                 from node_modules (a Vite dev server, esbuild, tauri dev) are stopped first
//   npm run clean -- --dry-run    list what would be removed, delete nothing
//
// Everything listed here is git-ignored and regenerated by `npm install`, `npm run build:*`, `npm run dev` /
// `npm test` (scripts/prepare.mjs) or `npm run build:icons`. Nothing tracked by git is touched. Afterwards the
// folder is compared with git: anything else that git does not keep is listed (never deleted). The database (in the app data folder, or data/ of `npm run web`) is never removed.
//
// Usage: node scripts/clean.mjs [--all] [--dry-run]
import { spawnSync } from 'node:child_process';
import { existsSync, readdirSync, rmSync, statSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const all = args.includes('--all');
const dryRun = args.includes('--dry-run') || args.includes('-n');

const targets = [
  ['dist', 'web bundle (npm run build:web)'],
  ['src-tauri/target', 'Rust build output and installers (cargo / tauri build)'],
  ['crates/mdcore/target', 'Rust core build output (cargo test)'],
  ['crates/mdwasm/target', 'Rust core WebAssembly build output (npm run build:wasm)'],
  ['public/mdcore.wasm', 'the Rust core as WebAssembly (scripts/prepare.mjs)'],
  ['public/doc', "user's guide and tutorial HTML (scripts/prepare.mjs, npm run build:docs)"],
  ['assets/icon.png', 'icon intermediate (npm run build:icons)'],
  ['assets/icon.icns', 'icon intermediate (npm run build:icons)'],
  ['assets/icon.ico', 'icon intermediate (npm run build:icons)'],
  ['assets/project.png', 'icon intermediate (npm run build:icons)'],
  ['src-tauri/gen', 'Tauri schemas generated by tauri-build'],
  ['src-tauri/runtime/desktop.cjs', 'staged desktop core (npm run stage)'],
  ['src-tauri/runtime/package.json', 'staged desktop core'],
  ['src-tauri/runtime/node.exe', 'staged Node executable'],
  ['src-tauri/runtime/node', 'staged Node executable'],
  ['release', 'installers collected by npm run build:*'],
  ['test-results', 'test reports (npm test)'],
  ['node_modules/.vite', 'Vite dependency cache'],
  ['.vite', 'Vite cache'],
];

// Installers that build:* copies to the project root, and stray logs (both git-ignored).
const rootFile = /^MyMarkdownMaster-.*\.(exe|msi|dmg|deb|rpm|AppImage)$|\.log$/i;
for (const name of readdirSync(rootDir)) {
  if (rootFile.test(name) && statSync(join(rootDir, name)).isFile()) {
    targets.push([name, name.endsWith('.log') ? 'log file' : 'installer copied to the project root']);
  }
}

if (all) targets.push(['node_modules', 'installed dependencies']);

/**
 * Processes running from this project's node_modules (a Vite dev server and its esbuild.exe, `tauri dev`, …).
 * On Windows a running executable cannot be deleted, so node_modules would stay half removed. Only programs
 * whose executable or command line lies inside <project>/node_modules are matched — never this script,
 * the npm that started it, or anything else.
 */
function processesUsingNodeModules() {
  const dir = join(rootDir, 'node_modules').toLowerCase();
  const own = new Set([process.pid, process.ppid]);
  let rows = [];
  try {
    if (process.platform === 'win32') {
      const ps = spawnSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command',
        'Get-CimInstance Win32_Process | ForEach-Object { "{0}`t{1}`t{2}`t{3}" -f $_.ProcessId, $_.ParentProcessId, $_.ExecutablePath, $_.CommandLine }'], { encoding: 'utf8', windowsHide: true, maxBuffer: 64 * 1024 * 1024 });
      rows = (ps.stdout ?? '').split(/\r?\n/).map((line) => { const [pid, ppid, exe, cmd] = line.split('\t'); return { pid: Number(pid), ppid: Number(ppid), text: `${exe ?? ''} ${cmd ?? ''}`, exe: exe ?? '' }; });
    } else {
      const ps = spawnSync('ps', ['-eo', 'pid=,ppid=,args='], { encoding: 'utf8' });
      rows = (ps.stdout ?? '').split('\n').map((line) => { const m = /^\s*(\d+)\s+(\d+)\s+(.*)$/.exec(line); return m ? { pid: Number(m[1]), ppid: Number(m[2]), text: m[3], exe: m[3].split(/\s+/)[0] } : null; }).filter(Boolean);
    }
  } catch {
    return [];
  }
  const norm = (s) => s.toLowerCase().replace(/\//g, '\\');
  const needle = process.platform === 'win32' ? norm(dir) : dir;
  const inside = (r) => (process.platform === 'win32' ? norm(r.text) : r.text.toLowerCase()).includes(needle);
  const isClean = (r) => /scripts[\\/]clean\.mjs/i.test(r.text);
  const byPid = new Map(rows.map((r) => [r.pid, r]));
  const found = new Map();
  for (const r of rows) {
    if (!r.pid || own.has(r.pid) || !inside(r) || isClean(r)) continue;
    found.set(r.pid, r);
    // Its starter, when that was started with a relative path (`node node_modules/vite/bin/vite.js`) — only
    // node itself: a terminal or shell that launched it is never stopped.
    for (let up = byPid.get(r.ppid), hops = 0; up && hops < 4 && !own.has(up.pid); up = byPid.get(up.ppid), hops += 1) {
      if (!/(^|[\\/])node(\.exe)?$/i.test(String(up.exe ?? '').trim()) || !/node_modules/i.test(up.text) || isClean(up)) break;
      found.set(up.pid, up);
    }
  }
  return [...found.values()];
}

function stopProcessesUsingNodeModules() {
  const found = processesUsingNodeModules();
  for (const p of found) {
    const name = p.text.trim().slice(0, 140);
    if (dryRun) { console.log(`[clean] would stop pid ${p.pid}  ${name}`); continue; }
    try {
      if (process.platform === 'win32') spawnSync(join(process.env.SystemRoot ?? 'C:\\Windows', 'System32', 'taskkill.exe'), ['/T', '/F', '/PID', String(p.pid)], { windowsHide: true });
      else process.kill(p.pid, 'SIGTERM');
      console.log(`[clean] stopped pid ${p.pid} (running from node_modules)  ${name}`);
    } catch { /* already gone */ }
  }
  if (found.length && !dryRun) spawnSync(process.execPath, ['-e', 'setTimeout(() => {}, 800)']); // let Windows release the files
}

if (all && existsSync(join(rootDir, 'node_modules'))) stopProcessesUsingNodeModules();

function sizeOf(path) {
  try {
    const st = statSync(path);
    if (!st.isDirectory()) return st.size;
    let total = 0;
    for (const entry of readdirSync(path, { withFileTypes: true })) {
      if (entry.isSymbolicLink()) continue;
      total += sizeOf(join(path, entry.name));
    }
    return total;
  } catch {
    return 0; // unreadable entries just do not count towards the total
  }
}

const mb = (bytes) => `${(bytes / 1024 / 1024).toFixed(1)} MB`;

let removed = 0;
let freed = 0;
let failed = 0;

for (const [rel, why] of targets) {
  const path = resolve(rootDir, rel);
  // Never step outside the project, whatever ends up in the list.
  if (path === rootDir || !path.startsWith(rootDir + sep)) continue;
  if (!existsSync(path)) continue;

  const bytes = sizeOf(path);
  const label = `${relative(rootDir, path).split(sep).join('/')}  (${why}, ${mb(bytes)})`;

  if (dryRun) {
    console.log(`[clean] would remove ${label}`);
    removed++;
    freed += bytes;
    continue;
  }
  try {
    rmSync(path, { recursive: true, force: true, maxRetries: 3, retryDelay: 200 });
    console.log(`[clean] removed ${label}`);
    removed++;
    freed += bytes;
  } catch (err) {
    // On Windows a running app or an open Explorer window keeps a handle open.
    console.error(`[clean] could not remove ${label}: ${err.message}`);
    failed++;
  }
}

if (!removed && !failed) {
  console.log('[clean] Nothing to remove - already clean.');
} else {
  console.log(dryRun
    ? `[clean] ${removed} item(s), ${mb(freed)} would be removed. Run without --dry-run to delete.`
    : `[clean] ${removed} item(s) removed, ${mb(freed)} freed.`);
  if (!all && !dryRun) console.log('[clean] node_modules/ kept - use "npm run clean:all" to remove it too.');
}

// What is left that git does not keep (ignored, or new and not added yet) is listed — never deleted — so
// nothing big hides from the clean. Paths come from `git status` relative to the repository's top folder.
if (!dryRun) {
  const top = spawnSync('git', ['rev-parse', '--show-toplevel'], { cwd: rootDir, encoding: 'utf8' });
  const status = top.status === 0 ? spawnSync('git', ['status', '--porcelain', '--ignored', '--untracked-files=normal', '--', '.'], { cwd: rootDir, encoding: 'utf8' }) : null;
  if (status?.status === 0) {
    const repo = top.stdout.trim();
    const extra = status.stdout.split(/\r?\n/)
      .filter((line) => line.startsWith('!! ') || line.startsWith('?? '))
      .map((line) => ({ kind: line.startsWith('!!') ? 'ignored' : 'not added to git', path: resolve(repo, line.slice(3).replace(/^"|"$/g, '')) }))
      .filter((x) => x.path.startsWith(rootDir + sep) && (all || x.path !== join(rootDir, 'node_modules')))
      .map((x) => ({ ...x, bytes: sizeOf(x.path) }));
    if (!extra.length) console.log(`[clean] The folder now holds only what git keeps${all ? '' : ' (and node_modules/)'}.`);
    else {
      console.log(`[clean] Not kept by git but left in place (${mb(extra.reduce((sum, x) => sum + x.bytes, 0))}) - remove by hand if not needed:`);
      for (const x of extra) console.log(`[clean]   ${relative(rootDir, x.path).split(sep).join('/')}  (${x.kind}, ${mb(x.bytes)})`);
    }
  }
}

if (failed) {
  console.error(`[clean] ${failed} item(s) could not be removed - close the app or Explorer windows using them and retry.`);
  process.exit(1);
}
