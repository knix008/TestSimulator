//! LaTeX: a compilable `article` (XeLaTeX/LuaLaTeX preferred; pdfLaTeX works for non-Korean text).
//! kotex for Korean, hyperref, graphicx, longtable+booktabs, listings (known languages) or verbatim,
//! amsmath/amssymb, framed boxes for alerts, ulem for strike-through, \tableofcontents, numbered or
//! starred sections, footnotes inline, math passed through natively.
use super::ir::{alert_title, plain, sole_image, strip_tags, Align, Block, Doc, Inline};
use super::util::{is_korean, is_url};
use super::ExportInput;

/// Escapes text for LaTeX (all ten special characters, plus a few that need a text-mode command).
pub fn esc(s: &str) -> String {
    let mut o = String::with_capacity(s.len() + 8);
    for c in s.chars() {
        match c {
            '\\' => o.push_str("\\textbackslash{}"),
            '{' => o.push_str("\\{"),
            '}' => o.push_str("\\}"),
            '$' => o.push_str("\\$"),
            '&' => o.push_str("\\&"),
            '%' => o.push_str("\\%"),
            '#' => o.push_str("\\#"),
            '_' => o.push_str("\\_"),
            '~' => o.push_str("\\textasciitilde{}"),
            '^' => o.push_str("\\textasciicircum{}"),
            '<' => o.push_str("\\textless{}"),
            '>' => o.push_str("\\textgreater{}"),
            '|' => o.push_str("\\textbar{}"),
            '"' => o.push_str("\\textquotedbl{}"),
            '\u{A0}' => o.push('~'),
            '\r' => {}
            c => o.push(c),
        }
    }
    o
}

/// Escapes a URL for \href / \url (only `\`, `#`, `%`, `{`, `}` need care).
fn url_esc(u: &str) -> String {
    let mut o = String::new();
    for c in u.chars() {
        match c {
            '\\' => o.push('/'),
            '#' => o.push_str("\\#"),
            '%' => o.push_str("\\%"),
            '{' => o.push_str("%7B"),
            '}' => o.push_str("%7D"),
            ' ' => o.push_str("%20"),
            c => o.push(c),
        }
    }
    o
}

