// npm run clean — removes everything a build or a test run produces, so the next build starts from scratch.
//
//   npm run clean                 build output, installers, staged data service, test results and caches
//   npm run clean:all             the above + node_modules/ (run `npm install` afterwards)
//   npm run clean -- --dry-run    list what would be removed, delete nothing
//
// Everything listed here is git-ignored and made again by `npm install`, `npm run build:*`, `npm run stage`
// or `npm test`. Nothing tracked by git is touched (src-tauri/runtime/.gitignore stays). The database is never
// removed: data/ (the development data service) and the installed app's data folder are left alone.
//
// Usage: node scripts/clean.mjs [--all] [--dry-run]
import { existsSync, readdirSync, rmSync, statSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const all = args.includes('--all');
const dryRun = args.includes('--dry-run') || args.includes('-n');

const targets = [
  ['dist', 'web bundle (npm run build:web)'],
  ['src-tauri/target', 'Rust build output and installers (cargo / tauri build)'],
  ['src-tauri/gen', 'Tauri schemas generated by tauri-build'],
  ['src-tauri/runtime/server.cjs', 'staged data service (npm run stage)'],
  ['src-tauri/runtime/package.json', 'staged data service'],
  ['src-tauri/runtime/node.exe', 'staged Node executable'],
  ['src-tauri/runtime/node', 'staged Node executable'],
  ['release', 'installers collected by a build'],
  ['test-results', 'test reports (npm test)'],
  ['node_modules/.vite', 'Vite dependency cache'],
  ['.vite', 'Vite cache'],
];

// Installers copied to the project root, and stray logs (both git-ignored).
const rootFile = /^MyWorkForce[-_].*\.(exe|msi|dmg|deb|rpm|AppImage)$|\.log$/i;
for (const name of readdirSync(rootDir)) {
  if (rootFile.test(name) && statSync(join(rootDir, name)).isFile()) {
    targets.push([name, name.endsWith('.log') ? 'log file' : 'installer copied to the project root']);
  }
}

if (all) targets.push(['node_modules', 'installed dependencies']);

function sizeOf(path) {
  try {
    const st = statSync(path);
    if (!st.isDirectory()) return st.size;
    let total = 0;
    for (const entry of readdirSync(path, { withFileTypes: true })) {
      if (entry.isSymbolicLink()) continue;
      total += sizeOf(join(path, entry.name));
    }
    return total;
  } catch {
    return 0; // an unreadable entry just does not count towards the total
  }
}

const size = (bytes) => (bytes >= 1024 ** 3 ? `${(bytes / 1024 ** 3).toFixed(2)} GB` : `${(bytes / 1024 / 1024).toFixed(1)} MB`);
const color = process.stdout.isTTY && !process.env.NO_COLOR;
const paint = (code, text) => (color ? `\x1b[${code}m${text}\x1b[0m` : text);

let removed = 0;
let freed = 0;
let failed = 0;

for (const [rel, why] of targets) {
  const path = resolve(rootDir, rel);
  // Never step outside the project, and never touch the database folder, whatever ends up in the list.
  if (path === rootDir || !path.startsWith(rootDir + sep)) continue;
  if (path === resolve(rootDir, 'data') || path.startsWith(resolve(rootDir, 'data') + sep)) continue;
  if (!existsSync(path)) continue;

  const bytes = sizeOf(path);
  const label = `${relative(rootDir, path).split(sep).join('/')}  ${paint('2', `(${why}, ${size(bytes)})`)}`;
  if (dryRun) {
    console.log(`${paint('36', '[clean]')} would remove ${label}`);
    removed += 1;
    freed += bytes;
    continue;
  }
  try {
    rmSync(path, { recursive: true, force: true, maxRetries: 3, retryDelay: 200 });
    console.log(`${paint('32', '[clean]')} removed ${label}`);
    removed += 1;
    freed += bytes;
  } catch (error) {
    failed += 1;
    console.log(`${paint('31', '[clean]')} could not remove ${relative(rootDir, path)}: ${error.code || error.message}`);
    if (error.code === 'EBUSY' || error.code === 'EPERM') console.log(paint('2', '        a running MyWorkForce, its data service or an editor may still hold it; close it and run again'));
  }
}

const verb = dryRun ? 'would free' : 'freed';
if (!removed && !failed) console.log(`${paint('32', '[clean]')} nothing to remove`);
else console.log(`${paint(failed ? '33' : '32', '[clean]')} ${removed} item${removed === 1 ? '' : 's'}, ${verb} ${size(freed)}${failed ? `, ${failed} failed` : ''}`);
if (all && !dryRun && !failed) console.log(paint('2', '[clean] run `npm install` before the next build or test'));
process.exit(failed ? 1 : 0);
