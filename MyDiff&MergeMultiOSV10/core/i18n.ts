export type StringKey = keyof typeof STRINGS;

/** Looks up a string and substitutes `{0}`, `{1}`, ... with `args`. */
export function translate(language: Language, key: StringKey, ...args: (string | number)[]): string {
  const entry = STRINGS[key] as readonly [string, string] | undefined;
  const text = entry ? entry[language === "en" ? 1 : 0] : String(key);
  return args.length === 0 ? text : text.replace(/\{(\d+)\}/g, (match, index) => String(args[Number(index)] ?? match));
}

/** Convenience binder: `const t = translator("ko"); t("menu.file")`. */
export function translator(language: Language) {
  return (key: StringKey, ...args: (string | number)[]) => translate(language, key, ...args);
}

export type Translate = ReturnType<typeof translator>;
