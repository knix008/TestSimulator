// The C of the MVVM layers, beside the screens codegen.js prints:
//
//   lib/mvvm/           the binding library (engine/mvvm), the same one the design engine runs
//   src/glue/           generated: one ViewModel per file, and glue.h for the application
//   src/ui/ui_bindings.c  generated: the bindings between widgets and ViewModel properties
//   src/app/            the application's own code: written once, when missing, never again
//
// The application includes only glue.h, which does not include lvgl.h: its logic can be
// built and tested without LVGL, and survives every change of the design.
import { MVVM_FILES } from "./mvvmSource.js";
import { viewModels, vmPrefix } from "./viewmodel.js";

export const GLUE_DIR = "src/glue";
export const APP_DIR = "src/app";
export const MVVM_DIR = "lib/mvvm";

const NOTE = "/* Generated by My LVGL Studio. Changes are overwritten when the project is saved. */";
const ATTR_C = ["MV_ATTR_VALUE", "MV_ATTR_TEXT", "MV_ATTR_CHECKED", "MV_ATTR_HIDDEN", "MV_ATTR_DISABLED"];
const MODE_C = ["MV_ONE_WAY", "MV_TWO_WAY", "MV_ONE_WAY_TO_SOURCE", "MV_ONE_TIME"];
const C_TYPE = { int: "int32_t", bool: "bool", string: "const char *" };
const GETTER = { int: "mv_get_int", bool: "mv_get_bool", string: "mv_get_string" };
const SETTER = { int: "mv_set_int", bool: "mv_set_bool", string: "mv_set_string" };

/** The C names of one ViewModel property. */
export function vmNames(vm, prop) {
  const prefix = vmPrefix(vm);
  return { prop: `${prefix}_prop_${prop.name}`, get: `${prefix}_get_${prop.name}`, set: `${prefix}_set_${prop.name}`, init: `${prefix}_init` };
}

/** Every C name the ViewModels declare, for the clash check of the problems view. */
export function glueIdentifiers(project) {
  const names = [];
  for (const vm of viewModels(project)) {
    names.push(`${vmPrefix(vm)}_init`);
    for (const prop of vm.props) {
      const c = vmNames(vm, prop);
      names.push(c.prop, c.get, c.set);
    }
  }
  return names;
}

function vmHeader(vm, cString) {
  const guard = `${vmPrefix(vm).toUpperCase()}_H`;
  const lines = [NOTE, `#ifndef ${guard}`, `#define ${guard}`, "", '#include "mvvm.h"', "", "#ifdef __cplusplus", 'extern "C" {', "#endif", "", `/* ViewModel ${vm.name}. */`, `void ${vmPrefix(vm)}_init(void);`, ""];
  for (const prop of vm.props) {
    const c = vmNames(vm, prop);
    const range = prop.type === "int" && prop.min < prop.max ? `, ${prop.min}..${prop.max}` : "";
    lines.push(
      `/* ${prop.name}: ${prop.type}${range}, starts as ${prop.type === "string" ? cString(prop.value) : String(prop.value)} */`,
      `${C_TYPE[prop.type]} ${c.get}(void);`,
      `void ${c.set}(${C_TYPE[prop.type]} value);`,
      `mv_prop_t * ${c.prop}(void);   /* for mv_observe() */`,
      "",
    );
  }
  lines.push("#ifdef __cplusplus", "}", "#endif", "", "#endif", "");
  return lines.join("\n");
}

function vmSource(vm, cString) {
  const prefix = vmPrefix(vm);
  const lines = [NOTE, `#include "${prefix}.h"`, ""];
  for (const prop of vm.props) lines.push(`static mv_prop_t ${prop.name}_prop;`);
  if (vm.props.length) lines.push("");
  lines.push(`void ${prefix}_init(void)`, "{");
  for (const prop of vm.props) {
    const own = `&${prop.name}_prop`;
    const name = cString(prop.name);
    if (prop.type === "int") {
      const ranged = Number.isInteger(prop.min) && Number.isInteger(prop.max);
      lines.push(`    mv_prop_init_int(${own}, ${name}, ${Math.trunc(Number(prop.value) || 0)}, ${ranged ? prop.min : 0}, ${ranged ? prop.max : 0});`);
    } else if (prop.type === "bool") lines.push(`    mv_prop_init_bool(${own}, ${name}, ${prop.value ? "true" : "false"});`);
    else lines.push(`    mv_prop_init_string(${own}, ${name}, ${cString(prop.value ?? "")});`);
  }
  lines.push("}", "");
  for (const prop of vm.props) {
    const c = vmNames(vm, prop);
    const own = `&${prop.name}_prop`;
    lines.push(
      `${C_TYPE[prop.type]} ${c.get}(void) { return ${GETTER[prop.type]}(${own}); }`,
      `void ${c.set}(${C_TYPE[prop.type]} value) { ${SETTER[prop.type]}(${own}, value); }`,
      `mv_prop_t * ${c.prop}(void) { return ${own}; }`,
      "",
    );
  }
  return lines.join("\n");
}

function glueHeader(project) {
  const lines = [
    NOTE,
    "/*",
    " * What the application sees of the screens: the ViewModels. Include this, never ui.h, in",
    " * the code of src/app. It does not include lvgl.h, so that code builds without LVGL too.",
    " */",
    "#ifndef GLUE_H",
    "#define GLUE_H",
    "",
    '#include "mvvm.h"',
  ];
  for (const vm of viewModels(project)) lines.push(`#include "${vmPrefix(vm)}.h"`);
  lines.push(
    "",
    "#ifdef __cplusplus",
    'extern "C" {',
    "#endif",
    "",
    "/* Gives every property its first value. ui_init() calls it; a test of the logic without",
    "   the screens calls it itself. A second call does nothing. */",
    "void glue_init(void);",
    "",
    "#ifdef __cplusplus",
    "}",
    "#endif",
    "",
    "#endif",
    "",
  );
  return lines.join("\n");
}

function glueSource(project) {
  const lines = [NOTE, '#include "glue.h"', "", "void glue_init(void)", "{", "    static bool done;", "    if(done) return;", "    done = true;"];
  for (const vm of viewModels(project)) lines.push(`    ${vmPrefix(vm)}_init();`);
  lines.push("}", "");
  return lines.join("\n");
}

/** src/ui/ui_bindings.c: one mv_bind() per binding, from the "bind" operations. */
export function bindingsSource(binds, nameOf, cString) {
  const lines = [NOTE, '#include "ui.h"', '#include "glue.h"', '#include "mvvm_lvgl.h"', "", "void ui_bindings_init(void)", "{"];
  for (const op of binds) {
    const widget = `${nameOf(op.id)}.${op.key}`;
    const model = `${op.vm}.${op.path}`;
    const flow = [`${model} -> ${widget}`, `${widget} <-> ${model}`, `${widget} -> ${model}`, `${model} -> ${widget}, once`][op.mode];
    const flags = [op.conv & 1 ? "MV_CONV_INVERT" : null, op.conv & 2 ? "MV_CONV_RANGE" : null].filter(Boolean).join(" | ") || "MV_CONV_NONE";
    const format = op.format ? cString(op.format) : "NULL";
    lines.push(
      `    /* ${flow} */`,
      `    mv_bind(${nameOf(op.id)}, ${vmNames(op.vm, { name: op.path }).prop}(), &(mv_binding_desc_t){ ${ATTR_C[op.attr]}, ${MODE_C[op.mode]}, ${flags}, ${op.viewMin}, ${op.viewMax}, ${format}, NULL, NULL, NULL });`,
    );
  }
  lines.push("}", "");
  return lines.join("\n");
}

/** The generated files of the MVVM layers (without ui_bindings.c, which codegen adds). */
export function glueFiles(project, cString) {
  const files = {};
  for (const [name, text] of Object.entries(MVVM_FILES)) files[`${MVVM_DIR}/${name}`] = text;
  files[`${GLUE_DIR}/glue.h`] = glueHeader(project);
  files[`${GLUE_DIR}/glue.c`] = glueSource(project);
  for (const vm of viewModels(project)) {
    files[`${GLUE_DIR}/${vmPrefix(vm)}.h`] = vmHeader(vm, cString);
    files[`${GLUE_DIR}/${vmPrefix(vm)}.c`] = vmSource(vm, cString);
  }
  return files;
}

/** The application's own files, as a new project gets them. Saving writes them only when missing. */
export function starterFiles(project) {
  const examples = [];
  const first = viewModels(project).find((vm) => vm.props.length);
  if (first) {
    const prop = first.props[0];
    const c = vmNames(first, prop);
    const sample = prop.type === "string" ? '"Hello"' : prop.type === "bool" ? "true" : "50";
    examples.push(
      " * For example, with the property " + `${first.name}.${prop.name}:`,
      ` *     ${c.set}(${sample});            every widget bound to it follows`,
      ` *     ${c.get}();                    what the user set on those widgets`,
      ` *     mv_observe(${c.prop}(), on_change, NULL);   told of every change`,
      " *     mv_timer_start(1000, every_second, NULL);           periodic work",
    );
  } else {
    examples.push(
      " * Add ViewModels in the studio (the ViewModels panel), bind widget properties to them, and",
      " * then use the functions src/glue/vm_<name>.h declares: vm_<name>_set_<property>(...).",
    );
  }
  return {
    [`${APP_DIR}/app.h`]: [
      "/* The application. My LVGL Studio writes this file once, when it is missing, and never again. */",
      "#ifndef APP_H",
      "#define APP_H",
      "",
      "#ifdef __cplusplus",
      'extern "C" {',
      "#endif",
      "",
      "/* Called once, after ui_init(): the screens and the ViewModels are ready. */",
      "void app_init(void);",
      "",
      "#ifdef __cplusplus",
      "}",
      "#endif",
      "",
      "#endif",
      "",
    ].join("\n"),
    [`${APP_DIR}/app.c`]: [
      "/*",
      " * The application logic. My LVGL Studio writes this file once, when it is missing, and never",
      " * changes it again: the design can change as much as it likes, this code stays. Every .c",
      " * and .cpp file in src/app is built with the project.",
      " *",
      " * Talk to the screens only through the ViewModels of glue.h: set a property and the bound",
      " * widgets follow; read one to see what the user did; observe one to hear of each change.",
      ...examples,
      " * Nothing here needs lvgl.h, so this code also builds, and can be tested, without LVGL.",
      " */",
      '#include "app.h"',
      '#include "glue.h"',
      "",
      "void app_init(void)",
      "{",
      "}",
      "",
    ].join("\n"),
  };
}
