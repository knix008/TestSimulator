// Copies the MVVM library (engine/mvvm) into src/lvgl/mvvmSource.js, from where the code
// generator writes it into every project as lib/mvvm/. One source, so the design engine and
// the generated program bind in the same way. A test fails when the two differ.
//   npm run mvvm-source
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const MVVM_SOURCES = ["mvvm.h", "mvvm.c", "mvvm_lvgl.h", "mvvm_lvgl.c"];

export function mvvmModule() {
  const files = Object.fromEntries(MVVM_SOURCES.map((name) => [name, fs.readFileSync(path.join(root, "engine", "mvvm", name), "utf8").replace(/\r\n/g, "\n")]));
  return `// Generated by scripts/generate-mvvm-source.mjs from engine/mvvm. Do not edit.\nexport const MVVM_FILES = ${JSON.stringify(files, null, 2)};\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(root, "src", "lvgl", "mvvmSource.js"), mvvmModule());
  console.log("src/lvgl/mvvmSource.js written");
}
