// Writes src/lvgl/confTemplates.js: each bundled engine version's own lv_conf_template.h, so the
// LVGL settings window works before any LVGL is installed. third_party/ is not in git; this file is.
// Run `npm run conf-templates` after adding an engine version.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { BUNDLED_ENGINES } from "../src/lvgl/versions.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export const templatePath = (version) => path.join(root, "third_party", `lvgl-${version}`, "lv_conf_template.h");

export function confTemplatesSource() {
  const body = BUNDLED_ENGINES.map((version) => `  ${JSON.stringify(version)}: ${JSON.stringify(fs.readFileSync(templatePath(version), "utf8").replace(/\r\n/g, "\n"))},`);
  return `// Generated by scripts/generate-conf-templates.mjs from LVGL's lv_conf_template.h (MIT licence).\nexport const CONF_TEMPLATES = {\n${body.join("\n")}\n};\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(root, "src", "lvgl", "confTemplates.js"), confTemplatesSource());
  console.log(`conf templates: ${BUNDLED_ENGINES.join(", ")}`);
}
