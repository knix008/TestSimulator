// Puts the user guide (UsersGuide.md, UsersGuide.en.md) where the guide window
// (public/doc/index.html) reads it: the text in public/doc/guide-content.js and
// the pictures it shows (docs/guide/images, made by make-guide-images.mjs) in
// public/doc/img/.
//   node scripts/build-guide.mjs          write them
//   node scripts/build-guide.mjs --check  fail when the text is out of date (tests)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'public', 'doc', 'guide-content.js');
const imgOut = path.join(root, 'public', 'doc', 'img');

const read = (name) => fs.readFileSync(path.join(root, name), 'utf8').replace(/\r\n/g, '\n');
const guides = () => ({ ko: read('UsersGuide.md'), en: read('UsersGuide.en.md') });

export function guideContent() {
  return `// Generated by scripts/build-guide.mjs from UsersGuide.md and UsersGuide.en.md. Do not edit.\nwindow.__MYPHOTO_GUIDE__ = ${JSON.stringify(guides())};\n`;
}

/** The local pictures the guides show (paths from the project root). */
export function guideImages() {
  const all = Object.values(guides()).flatMap((text) => [...text.matchAll(/!\[[^\]]*\]\(([^)\s]+)\)/g)].map((m) => m[1]));
  return [...new Set(all.filter((src) => !/^https?:/.test(src)))];
}

export function writeGuide() {
  fs.mkdirSync(imgOut, { recursive: true });
  fs.writeFileSync(out, guideContent());
  for (const src of guideImages()) fs.copyFileSync(path.join(root, src), path.join(imgOut, path.basename(src)));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (now !== guideContent()) {
      console.error('public/doc/guide-content.js is out of date: run node scripts/build-guide.mjs');
      process.exit(1);
    }
  } else {
    writeGuide();
    console.log(`wrote ${path.relative(root, out)} and ${guideImages().length} pictures in ${path.relative(root, imgOut)}`);
  }
}
