const dicts = { ko, en };

function render(lang, key, params) {
  const d = dicts[lang] || ko;
  let s = d[key] !== undefined ? d[key] : (ko[key] !== undefined ? ko[key] : String(key));
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

module.exports = { render, dicts };
