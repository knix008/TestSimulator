// ifcXML (ISO 10303-28): IFC written as XML instead of STEP text. Both
// flavours in use are read and written:
//
//   IFC4 ifcXML    <ifcXML xmlns=".../ifcXML/IFC4/Add2"> — simple values as
//                  XML attributes (Name="…", Coordinates="0 0 0"), entity
//                  values as elements carrying id / ref (xsi:type for a
//                  subtype), select values in "-wrapper" elements.
//   IFC2x3 ifcXML  <ex:iso_10303_28><uos configuration="i_ifc2x3"> — every
//                  attribute an element, entities referenced inside them,
//                  lists of IfcLengthMeasure / ex:double-wrapper items.
//
// Reading turns the XML into the same entity graph the STEP reader builds
// (Map id → {type, args} with the attributes in schema order), so all of the
// IFC import in ifc.js is reused. Writing goes the other way from our own
// IFC export. The attribute order and types come from the official EXPRESS
// schemas (ifcschema.js, generated by scripts/gen-ifcschema.mjs).

import { IFC4, IFC2X3 } from "./ifcschema.js";
import { parseXml } from "./svgimport.js";
import { exportIfc, parseStep, importIfcEntities } from "./ifc.js";

const up = (s) => String(s).toUpperCase();
const local = (n) => String(n || "").replace(/^.*:/, "");
const BUILTIN_ITEMS = { double: "r", real: "r", long: "i", integer: "i", string: "s", boolean: "b", logical: "l", hexBinary: "x", binary: "x", number: "r" };

// ---------------------------------------------------------------- schema
const models = {};
export function schemaModel(key) {
  const k = key === "IFC2X3" ? "IFC2X3" : "IFC4";
  if (models[k]) return models[k];
  const src = k === "IFC2X3" ? IFC2X3 : IFC4;
  const types = new Map();
  const names = new Map(); // UPPER → CamelCase (types and entities)
  for (const kv of src.T.split(";")) {
    const i = kv.indexOf("=");
    const name = kv.slice(0, i);
    types.set(up(name), kv.slice(i + 1));
    names.set(up(name), name);
  }
  const raw = new Map();
  for (const line of src.E.split("\n")) {
    let rest = line;
    let inv = "", der = "";
    const t = rest.indexOf("~");
    if (t >= 0) { inv = rest.slice(t + 1); rest = rest.slice(0, t); }
    const h = rest.indexOf("#");
    if (h >= 0) { der = rest.slice(h + 1); rest = rest.slice(0, h); }
    const parts = rest.split("|");
    const [name, supRaw] = parts[0].split("<");
    const abstract = supRaw.endsWith("!");
    const sup = supRaw.replace(/!$/, "") || null;
    const attrs = parts.slice(1).map((p) => {
      const i = p.indexOf("=");
      const opt = p.endsWith("?");
      return { name: p.slice(0, i), type: p.slice(i + 1, opt ? -1 : undefined), opt };
    });
    const inverse = inv ? inv.split(",").map((s) => { const [n, r] = s.split("="); const [entity, forAttr] = r.replace(/!$/, "").split("."); return { name: n, entity, forAttr, one: r.endsWith("!") }; }) : [];
    raw.set(up(name), { name, sup: sup ? up(sup) : null, abstract, attrs, derived: der ? der.split(",") : [], inverse });
    names.set(up(name), name);
  }
  const ents = new Map();
  const full = (U) => {
    if (ents.has(U)) return ents.get(U);
    const r = raw.get(U);
    if (!r) return null;
    const base = r.sup ? full(r.sup) : null;
    const attrs = [...(base ? base.attrs.map((a) => ({ ...a })) : []), ...r.attrs.map((a) => ({ ...a, decl: U }))];
    for (const d of r.derived) { const a = attrs.find((x) => x.name === d); if (a) a.derived = true; }
    const inv = new Map(base ? base.inv : []);
    for (const i of r.inverse) inv.set(i.name, { entity: up(i.entity), forAttr: i.forAttr, one: i.one });
    const e = { type: U, name: r.name, abstract: r.abstract, sup: r.sup, attrs, inv, index: new Map(attrs.map((a, i) => [a.name, i])), own: r.attrs.map((a) => a.name), order: null };
    ents.set(U, e);
    return e;
  };
  for (const U of raw.keys()) full(U);
  // IFC4 ifcXML: attributes written through an inverse element of the owner,
  // and the element order of the levels carrying inverse elements.
  const suppressed = new Set((src.X || "").split(";").filter(Boolean).map((x) => { const [e, a] = x.split("."); return `${up(e)}.${a}`; }));
  for (const o of (src.O || "").split(";").filter(Boolean)) { const [e, list] = o.split(":"); const d = ents.get(up(e)); if (d) { d.order = list.split(",").map((n) => n.replace(/!$/, "")); d.single = new Set(list.split(",").filter((n) => n.endsWith("!")).map((n) => n.slice(0, -1))); } }
  const kinds = new Map();
  // Descriptor → {agg, inner} | {base, typeName} | {entity}.
  const kindOf = (desc) => {
    if (kinds.has(desc)) return kinds.get(desc);
    let k;
    if (desc.startsWith("L:") || desc.startsWith("S:")) k = { agg: desc[0], inner: desc.slice(2) };
    else if (desc.length === 1) k = { base: desc };
    else {
      const t = types.get(up(desc));
      if (t !== undefined) { const b = kindOf(t); k = { ...b, typeName: b.typeName || names.get(up(desc)) }; } else k = { entity: names.get(up(desc)) || desc };
    }
    kinds.set(desc, k);
    return k;
  };
  const isSub = (U, of) => { for (let e = ents.get(U); e; e = e.sup ? ents.get(e.sup) : null) if (e.type === of) return true; return false; };
  models[k] = { key: k, types, names, ents, kindOf, isSub, suppressed };
  return models[k];
}

// ================================================================ reading
const childEls = (el) => (el.children || []).filter((c) => c.name);
const textOf = (el) => (el.children || []).map((c) => (c.text !== undefined ? c.text : textOf(c))).join("");
const META_ATTRS = /^(id|ref|pos|href|path|xsi:.*|xmlns.*|ex:.*|ifc:.*|cType|itemType|arraySize)$/;
const hasContent = (el) => childEls(el).length > 0 || Object.keys(el.attrs).some((a) => !META_ATTRS.test(a));

function decodeText(input) {
  if (typeof input === "string") return input.replace(/^﻿/, "");
  const b = input instanceof Uint8Array ? input : new Uint8Array(input);
  let enc = "utf-8";
  if ((b[0] === 0xff && b[1] === 0xfe) || (b[0] === 0x3c && b[1] === 0)) enc = "utf-16le";
  else if ((b[0] === 0xfe && b[1] === 0xff) || (b[0] === 0 && b[1] === 0x3c)) enc = "utf-16be";
  return new TextDecoder(enc).decode(b).replace(/^﻿/, "");
}

// Is this text (its start) an ifcXML document?
export const looksLikeIfcXml = (text) => /<(?:\w+:)?(?:ifcXML|iso_10303_28)[\s>]/.test(String(text).slice(0, 4096));

class XmlReader {
  constructor(m) {
    this.m = m;
    this.ids = new Map();
    this.next = 1;
    this.entities = new Map();
    this.unknown = new Map();
    this.patches = [];
  }

  id(s) { if (!this.ids.has(s)) this.ids.set(s, this.next++); return this.ids.get(s); }

  // An entity element (top level, inline in an attribute, or an item) → {ref}.
  entity(el, typeName) {
    const m = this.m;
    const U = up(local(typeName));
    const def = m.ents.get(U);
    if (el.attrs.ref !== undefined && !hasContent(el)) return { ref: this.id(el.attrs.ref) };
    if (!def || def.abstract) { this.unknown.set(local(typeName), (this.unknown.get(local(typeName)) || 0) + 1); return el.attrs.ref !== undefined ? { ref: this.id(el.attrs.ref) } : null; }
    const key = el.attrs.id ?? el.attrs.ref;
    const id = key !== undefined ? this.id(key) : this.next++;
    if (this.entities.has(id) && el.attrs.id === undefined) return { ref: id };
    const args = def.attrs.map(() => null);
    this.entities.set(id, { type: U, args });
    const byName = new Map();
    for (const c of childEls(el)) { const n = local(c.name); if (!byName.has(n)) byName.set(n, c); }
    const prev = this.cur;
    this.cur = def;
    def.attrs.forEach((a, i) => {
      if (a.derived) return;
      if (el.attrs[a.name] !== undefined) args[i] = this.simple(el.attrs[a.name], a.type);
      else if (byName.has(a.name)) args[i] = this.attr(byName.get(a.name), a.type);
    });
    this.cur = prev;
    // Inverse attributes written inside their owner (IsDecomposedBy, IsDefinedBy…):
    // the nested relationship points back to this entity.
    for (const c of childEls(el)) {
      const n = local(c.name);
      const inv = def.inv.get(n);
      if (!inv || def.index.has(n)) continue;
      const kids = childEls(c);
      const items = kids.length && kids.every((k) => m.ents.has(up(local(k.attrs["xsi:type"] || k.name))) && !m.ents.get(inv.entity).index.has(local(k.name)))
        ? kids.map((k) => this.entity(k, k.attrs["xsi:type"] || k.name))
        : [this.entity(c, c.attrs["xsi:type"] || m.names.get(inv.entity))];
      for (const r of items) if (r) this.patches.push([r.ref, inv.forAttr, id]);
    }
    return { ref: id };
  }

  // An attribute element → value.
  attr(el, desc) {
    const m = this.m;
    const k = m.kindOf(desc);
    if (el.attrs.ref !== undefined && !hasContent(el)) return { ref: this.id(el.attrs.ref) };
    if (el.attrs["xsi:nil"] === "true" && !hasContent(el)) return null;
    const kids = childEls(el);
    if (k.agg) {
      if (!kids.length) return this.simple(textOf(el), desc);
      let items = kids;
      if (items.every((c) => c.attrs.pos !== undefined) && new Set(items.map((c) => c.attrs.pos)).size === items.length) items = items.slice().sort((a, b) => +a.attrs.pos - +b.attrs.pos);
      return items.map((c) => this.item(c, k.inner));
    }
    if (k.entity || k.base === "S") {
      const xt = el.attrs["xsi:type"];
      if (kids.length && this.isTypeName(local(kids[0].name)) && !(k.entity && (m.ents.get(up(k.entity)) || { index: new Map() }).index.has(local(kids[0].name)))) return this.item(kids[0], desc);
      if (xt) {
        const n = local(xt);
        if (m.ents.has(up(n))) return this.entity(el, n);
        if (m.types.has(up(n))) return { typed: up(n), value: this.simple(textOf(el), n) };
      }
      if (k.entity) return this.entity(el, k.entity);
      const s = textOf(el).trim();
      return s === "" ? null : s;
    }
    return this.simple(textOf(el), desc);
  }

  isTypeName(n) {
    const b = n.replace(/-wrapper$/, "");
    return this.m.ents.has(up(b)) || this.m.types.has(up(b)) || BUILTIN_ITEMS[b] !== undefined;
  }

  // One element of a list or a select → value.
  item(el, desc) {
    const m = this.m;
    const n = local(el.name).replace(/-wrapper$/, "");
    if (el.attrs.ref !== undefined && !hasContent(el)) return { ref: this.id(el.attrs.ref) };
    if (m.ents.has(up(n)) || (el.attrs["xsi:type"] && m.ents.has(up(local(el.attrs["xsi:type"]))))) return this.entity(el, el.attrs["xsi:type"] || n);
    const k = m.kindOf(desc);
    if (m.types.has(up(n))) {
      const tk = m.kindOf(n);
      const v = tk.agg || tk.base === "S" ? this.attr(el, n) : this.simple(textOf(el), n);
      return k.base === "S" ? { typed: up(n), value: v } : v;
    }
    if (BUILTIN_ITEMS[n]) return this.simple(textOf(el), BUILTIN_ITEMS[n]);
    return k.agg ? this.attr(el, desc) : this.simple(textOf(el), desc);
  }

  // Text of a simple value (or a space separated list of them) → value.
  simple(str, desc) {
    const k = this.m.kindOf(desc);
    const s = String(str ?? "");
    if (k.agg) {
      const parts = s.trim().split(/\s+/).filter(Boolean);
      const ik = this.m.kindOf(k.inner);
      if (ik.agg) {
        // A list of lists written flat (IFC4 CoordList, CoordIndex…).
        const nm = this.cur ? this.cur.name : "";
        const w = /2D$|TexCoords|TexCoordList/i.test(nm) ? 2 : 3;
        const out = [];
        for (let i = 0; i < parts.length; i += w) out.push(parts.slice(i, i + w).map((p) => this.simple(p, ik.inner)));
        return out;
      }
      return parts.map((p) => this.simple(p, k.inner));
    }
    const t = s.trim();
    switch (k.base) {
      case "r": case "i": { if (t === "") return null; const v = parseFloat(t); return Number.isFinite(v) ? v : null; }
      case "b": return { enum: /^(true|t|\.t\.|1)$/i.test(t) ? "T" : "F" };
      case "l": return { enum: /^(true|t|\.t\.)$/i.test(t) ? "T" : /^(false|f|\.f\.)$/i.test(t) ? "F" : "U" };
      case "e": return t === "" ? null : { enum: up(t) };
      case "s": case "x": return s;
      default: return t === "" ? null : s;
    }
  }

  finish() {
    for (const [target, forAttr, owner] of this.patches) {
      const e = this.entities.get(target);
      if (!e) continue;
      const def = this.m.ents.get(e.type);
      const i = def.index.get(forAttr);
      if (i === undefined) continue;
      const k = this.m.kindOf(def.attrs[i].type);
      if (k.agg) {
        if (!Array.isArray(e.args[i])) e.args[i] = [];
        if (!e.args[i].some((r) => r && r.ref === owner)) e.args[i].push({ ref: owner });
      } else if (e.args[i] === null) e.args[i] = { ref: owner };
    }
  }
}

// Which schema an ifcXML document is written in.
function schemaOf(root, uos) {
  const said = [root, uos].filter(Boolean).flatMap((el) => Object.entries(el.attrs).filter(([k]) => /^xmlns|configuration|express|schemaLocation/.test(k)).map(([, v]) => v)).join(" ");
  if (/IFC2x3|ifc2x3/i.test(said)) return "IFC2X3";
  if (/IFC4/i.test(said)) return "IFC4";
  return local(root.name) === "iso_10303_28" ? "IFC2X3" : "IFC4";
}

// ifcXML text or bytes → {entities, header, schema, errors, unknown}.
export function parseIfcXml(input) {
  const text = decodeText(input);
  const doc = parseXml(text);
  const root = childEls(doc)[0];
  if (!root || !/^(ifcXML|iso_10303_28|uos)$/.test(local(root.name))) {
    const e = new Error("This is not an ifcXML file.");
    e.code = "ifcxml-not";
    throw e;
  }
  const uos = local(root.name) === "uos" ? root : childEls(root).find((c) => local(c.name) === "uos") || null;
  const schema = schemaOf(root, uos);
  const r = new XmlReader(schemaModel(schema));
  const body = uos || root;
  for (const el of childEls(body)) {
    const n = local(el.name);
    if (/header$/i.test(n) || n === "uos") continue;
    r.entity(el, el.attrs["xsi:type"] || n);
  }
  if (uos && uos !== root) for (const el of childEls(root)) if (el !== uos && !/header$/i.test(local(el.name)) && local(el.name) !== "uos") r.entity(el, local(el.name));
  r.finish();
  const head = childEls(root).find((c) => /header$/i.test(local(c.name)));
  const hv = (k) => { const el = head && childEls(head).find((c) => local(c.name) === k); return el ? textOf(el).trim() : ""; };
  const header = { FILE_SCHEMA: [[schema]], FILE_NAME: [hv("name"), hv("time_stamp"), [hv("author")], [hv("organization")], hv("preprocessor_version"), hv("originating_system"), hv("authorization")] };
  return { entities: r.entities, header, schema, errors: 0, unknown: r.unknown };
}

// ifcXML → {project, warnings, stats} through the IFC reader.
export function importIfcXml(input) {
  const { entities, header, unknown } = parseIfcXml(input);
  const res = importIfcEntities({ entities, header, errors: 0 });
  const odd = [...unknown].filter(([n]) => !/^(header|uos)$/i.test(n));
  if (odd.length) res.warnings.push(`${odd.reduce((s, [, n]) => s + n, 0)} ifcXML elements of unknown types were ignored (${odd.slice(0, 5).map(([n]) => n).join(", ")}${odd.length > 5 ? "…" : ""})`);
  return res;
}

// ================================================================ writing
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;")
  .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, "").replace(/\r/g, "&#13;").replace(/\n/g, "&#10;").replace(/\t/g, "&#9;");
const escText = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, "");
const fmtNum = (v) => (Number.isFinite(v) ? String(v) : "0");
const isRef = (v) => v && typeof v === "object" && !Array.isArray(v) && "ref" in v;
const isTyped = (v) => v && typeof v === "object" && !Array.isArray(v) && "typed" in v;
const isEnum = (v) => v && typeof v === "object" && !Array.isArray(v) && "enum" in v;

class XmlWriter {
  constructor(m, entities) {
    this.m = m;
    this.ents = entities;
    this.v4 = m.key === "IFC4";
    this.out = [];
    this.carriers = new Map(); // owner id → Map(inverse element name → [relationship ids])
    if (this.v4) this.prepare();
  }

  // IFC4: relationships whose pointer to their owner is left out of the XSD
  // (RelatingObject, Item…) are listed in the owner's inverse element.
  prepare() {
    const m = this.m;
    const exposed = (d, name) => { for (let x = d; x; x = x.sup ? m.ents.get(x.sup) : null) if (x.order && x.order.includes(name)) return true; return false; };
    for (const [rid, e] of this.ents) {
      const def = m.ents.get(e.type);
      if (!def) continue;
      def.attrs.forEach((a, i) => {
        if (!m.suppressed.has(`${a.decl}.${a.name}`)) return;
        const v = e.args[i];
        for (const r of (Array.isArray(v) ? v : [v]).filter(isRef)) {
          const owner = this.ents.get(r.ref);
          const od = owner && m.ents.get(owner.type);
          if (!od) continue;
          const name = [...od.inv].find(([n, inv]) => inv.forAttr === a.name && m.isSub(e.type, inv.entity) && exposed(od, n));
          if (!name) continue;
          if (!this.carriers.has(r.ref)) this.carriers.set(r.ref, new Map());
          const map = this.carriers.get(r.ref);
          if (!map.has(name[0])) map.set(name[0], []);
          map.get(name[0]).push(rid);
        }
      });
    }
  }

  typeName(id) { const e = this.ents.get(id); return e ? this.m.names.get(e.type) || e.type : "IfcRoot"; }

  // A simple value as text, by its base kind.
  simpleText(v, base) {
    if (isEnum(v)) {
      const e = v.enum;
      if (base === "b" || base === "l") return e === "T" ? "true" : e === "F" ? "false" : "unknown";
      return e.toLowerCase();
    }
    if (typeof v === "number") return base === "i" ? String(Math.round(v)) : fmtNum(v);
    if (typeof v === "boolean") return v ? "true" : "false";
    return String(v ?? "");
  }

  flat(v) { return Array.isArray(v) ? v.flatMap((x) => this.flat(x)) : [v]; }

  // Is every leaf of an aggregate descriptor a number (written as one XML attribute in IFC4)?
  numericList(desc) {
    let k = this.m.kindOf(desc);
    while (k.agg) k = this.m.kindOf(k.inner);
    return k.base === "r" || k.base === "i";
  }

  ref(id, tag) { return `<${tag} ref="i${id}" xsi:nil="true"/>`; }

  // An item of a list / a select's chosen value.
  item(v, desc, pad) {
    const m = this.m;
    if (isRef(v)) return `${pad}${this.ref(v.ref, this.typeName(v.ref))}`;
    const k = m.kindOf(desc);
    if (isTyped(v)) {
      const tn = m.names.get(v.typed) || v.typed;
      const tk = m.kindOf(tn);
      const tag = this.v4 || tk.agg ? `${tn}-wrapper` : tn;
      const body = Array.isArray(v.value) ? this.flat(v.value).map((x) => this.simpleText(x, m.kindOf(tk.inner || "r").base)).join(" ") : this.simpleText(v.value, tk.base);
      return `${pad}<${this.v4 ? tag : tn}>${escText(body)}</${this.v4 ? tag : tn}>`;
    }
    if (Array.isArray(v)) {
      // A list inside a list (2x3: a nested aggregate element).
      const inner = k.agg ? k.inner : desc;
      return `${pad}<ex:${this.numericList(inner) ? "double" : "string"}-wrapper>${escText(this.flat(v).map((x) => this.simpleText(x, "r")).join(" "))}</ex:${this.numericList(inner) ? "double" : "string"}-wrapper>`;
    }
    // A plain simple value in a list.
    const tn = k.typeName;
    const base = k.base;
    const tag = tn ? (this.v4 ? `${tn}-wrapper` : tn) : `ex:${{ r: "double", i: "long", s: "string", b: "boolean", l: "logical", x: "hexBinary" }[base] || "string"}-wrapper`;
    return `${pad}<${tag}>${escText(this.simpleText(v, base))}</${tag}>`;
  }

  entity(id, e) {
    const m = this.m;
    const def = m.ents.get(e.type);
    if (!def) return;
    const name = def.name;
    const xa = [];
    const parts = new Map(); // attribute name → element lines
    const pad = "    ";
    def.attrs.forEach((a, i) => {
      const v = e.args[i];
      if (a.derived || v === null || v === undefined || (v && v.derived)) return;
      if (this.v4 && m.suppressed.has(`${a.decl}.${a.name}`)) return; // written by the owner (see carriers)
      const k = m.kindOf(a.type);
      const kids = [];
      parts.set(a.name, kids);
      if (this.v4) {
        if (k.agg) {
          const list = Array.isArray(v) ? v : [v];
          if (!list.length) return;
          if (this.numericList(a.type)) { xa.push(`${a.name}="${this.flat(list).map((x) => this.simpleText(x, "r")).join(" ")}"`); return; }
          kids.push(`  <${a.name}>`, ...list.map((x) => this.item(x, k.inner, pad)), `  </${a.name}>`);
        } else if (k.entity) {
          if (isRef(v)) kids.push(`  <${a.name} ref="i${v.ref}" xsi:type="${this.typeName(v.ref)}" xsi:nil="true"/>`);
        } else if (k.base === "S") {
          kids.push(`  <${a.name}>`, this.item(v, a.type, pad), `  </${a.name}>`);
        } else if (Array.isArray(v)) {
          // A defined type that is itself a list (IfcCompoundPlaneAngleMeasure).
          xa.push(`${a.name}="${this.flat(v).map((x) => this.simpleText(x, "i")).join(" ")}"`);
        } else xa.push(`${a.name}="${esc(this.simpleText(v, k.base))}"`);
      } else if (k.agg || Array.isArray(v)) {
        const list = Array.isArray(v) ? v : [v];
        if (!list.length) return;
        const inner = k.agg ? k.inner : (m.kindOf(a.type).inner || "i");
        const ik = m.kindOf(inner);
        const lines = list.map((x) => {
          if (isRef(x) || isTyped(x) || Array.isArray(x)) return this.item(x, inner, pad);
          const tag = ik.typeName && !ik.agg ? ik.typeName : `ex:${{ r: "double", i: "long", s: "string", b: "boolean", l: "logical" }[ik.base] || "double"}-wrapper`;
          return `${pad}<${tag}>${escText(this.simpleText(x, ik.base))}</${tag}>`;
        });
        kids.push(`  <${a.name}>`, ...lines, `  </${a.name}>`);
      } else if (k.entity || k.base === "S") {
        kids.push(`  <${a.name}>`, this.item(v, a.type, pad), `  </${a.name}>`);
      } else kids.push(`  <${a.name}>${escText(this.simpleText(v, k.base))}</${a.name}>`);
    });
    const kids = [];
    if (!this.v4) for (const a of def.attrs) kids.push(...(parts.get(a.name) || []));
    else {
      // Level by level from the root type, in the XSD element order where
      // a level also carries inverse elements.
      const chain = [];
      for (let d = def; d; d = d.sup ? m.ents.get(d.sup) : null) chain.unshift(d);
      const mine = this.carriers.get(id);
      for (const L of chain) {
        for (const n of L.order || L.own) {
          if (parts.has(n) && L.own.includes(n)) { kids.push(...parts.get(n)); continue; }
          const rels = mine && mine.get(n);
          if (!rels || !rels.length) continue;
          // IFC4_ADD2.xsd allows one HasOpenings / HasFillings element where
          // EXPRESS has a set: more than one is written repeated.
          if (L.single && L.single.has(n)) for (const r of rels) kids.push(`  <${n} ref="i${r}" xsi:type="${this.typeName(r)}" xsi:nil="true"/>`);
          else kids.push(`  <${n}>`, ...rels.map((r) => `${pad}${this.ref(r, this.typeName(r))}`), `  </${n}>`);
        }
      }
    }
    const open = `<${name} id="i${id}"${xa.length ? ` ${xa.join(" ")}` : ""}`;
    if (!kids.length) this.out.push(`${open}/>`);
    else this.out.push(`${open}>`, ...kids, `</${name}>`);
  }
}

const NS4 = "http://www.buildingsmart-tech.org/ifcXML/IFC4/Add2";
const NS2 = "http://www.iai-tech.org/ifcXML/IFC2x3/FINAL";
const NSEX = "urn:iso.org:standard:10303:part(28):version(2):xmlschema:common";

// IFC STEP text (our own export or any file) → ifcXML text in its schema.
export function stepToIfcXml(stepText, { schema = null, name = "", author = "", organization = "", application = "MyArchitecture", timestamp } = {}) {
  const ents = parseStep(stepText);
  const declared = /FILE_SCHEMA\s*\(\s*\(\s*'([^']+)'/i.exec(stepText);
  const key = up(schema || (declared ? declared[1] : "IFC4")).startsWith("IFC2X3") ? "IFC2X3" : "IFC4";
  const m = schemaModel(key);
  const w = new XmlWriter(m, ents);
  const ts = (timestamp || new Date().toISOString()).slice(0, 19);
  const head = (p) => [
    `${p}name>${escText(name)}</${p}name>`, `${p}time_stamp>${escText(ts)}</${p}time_stamp>`, `${p}author>${escText(author)}</${p}author>`,
    `${p}organization>${escText(organization)}</${p}organization>`, `${p}preprocessor_version>${escText(application)}</${p}preprocessor_version>`,
    `${p}originating_system>${escText(application)}</${p}originating_system>`, `${p}authorization></${p}authorization>`,
    `${p}documentation>ViewDefinition [${key === "IFC4" ? "ReferenceView_V1.2" : "CoordinationView_V2.0"}]</${p}documentation>`,
  ].map((s) => `  <${s}`);
  for (const [id, e] of [...ents].sort((a, b) => a[0] - b[0])) w.entity(id, e);
  const body = w.out.map((s) => `  ${s}`);
  if (key === "IFC4") {
    return [
      '<?xml version="1.0" encoding="UTF-8"?>',
      `<ifcXML xmlns="${NS4}" xmlns:ifc="${NS4}" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns:xlink="http://www.w3.org/1999/xlink" xsi:schemaLocation="${NS4} http://www.buildingsmart-tech.org/ifc/IFC4/Add2/IFC4_ADD2.xsd" id="uos_1" express="http://www.buildingsmart-tech.org/ifc/IFC4/Add2/IFC4_ADD2.exp" configuration="http://www.buildingsmart-tech.org/ifc/IFC4/Add2/IFC4_ADD2_config.xml">`,
      "  <header>", ...head("").map((s) => `  ${s}`), "  </header>",
      ...body,
      "</ifcXML>", "",
    ].join("\n");
  }
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    `<ex:iso_10303_28 xmlns:ex="${NSEX}" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns:xlink="http://www.w3.org/1999/xlink" xsi:schemaLocation="${NSEX} http://www.iai-tech.org/ifcXML/IFC2x3/FINAL/ex.xsd" version="2.0">`,
    "  <ex:iso_10303_28_header>", ...head("ex:").map((s) => `  ${s}`), "  </ex:iso_10303_28_header>",
    `  <uos id="uos_1" description="${esc(name)}" configuration="i_ifc2x3" edo="" xmlns="${NS2}" xmlns:ex="${NSEX}" xsi:schemaLocation="${NS2} http://www.iai-tech.org/ifcXML/IFC2x3/FINAL/IFC2X3.xsd">`,
    ...body.map((s) => `  ${s}`),
    "  </uos>",
    "</ex:iso_10303_28>", "",
  ].join("\n");
}

// `project` → ifcXML text. schema: "IFC4" (default) or "IFC2X3".
export function exportIfcXml(project, opts = {}) {
  const schema = up(opts.schema || "IFC4").replace(/\s/g, "") === "IFC2X3" ? "IFC2X3" : "IFC4";
  const step = exportIfc(project, { ...opts, schema });
  return stepToIfcXml(step, { ...opts, schema, name: opts.name ?? (project.meta && project.meta.title) ?? "" });
}
