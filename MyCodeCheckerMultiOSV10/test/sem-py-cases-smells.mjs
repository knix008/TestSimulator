// sem-py samples: code smells (core/sem-py/rules/scoperules.js and smells.js).
// Each bad sample marks every line that must be reported with "# Noncompliant".

const L = (...lines) => lines.join('\n') + '\n';

// a function with `count` simple statements
function longFunction(name, count, marker) {
  const out = [`def ${name}(values):${marker ? '  # Noncompliant' : ''}`, '    total = 0'];
  for (let i = 0; i < count; i++) out.push(`    total += values[${i % 10}] * ${i + 1}`);
  out.push('    return total');
  return out;
}

function manyMethods(name, count, marker) {
  const out = [`class ${name}:${marker ? '  # Noncompliant' : ''}`, '    def __init__(self):', '        self.data = {}', ''];
  for (let i = 1; i < count; i++) out.push(`    def get_${i}(self):`, `        return self.data.get(${i})`, '');
  return out;
}

function bigFile(lines, marker) {
  const out = [marker ? '# Noncompliant' : '"""Generated lookup table."""', 'TABLE = {}'];
  for (let i = 0; i < lines; i++) out.push(`TABLE[${i}] = ${i * 3} + len(TABLE)`);
  return out.join('\n') + '\n';
}

