'use strict';

// Helpers shared by the rule modules.

const { unparen, dotted, callName, callTarget, hasMod, attrNamed, enclosing, forEachChild } = require('./ast');

// compile-time string value of a literal or a + concatenation of literals
function strVal(e) {
  e = unparen(e);
  if (!e) return null;
  if (e.k === 'Literal' && e.kind === 'string') return e.value;
  if (e.k === 'Binary' && e.op === '+') {
    const l = strVal(e.left); const r = strVal(e.right);
    if (l != null && r != null) return l + r;
  }
  return null;
}

function numVal(e) {
  e = unparen(e);
  if (!e) return null;
  if (e.k === 'Literal' && (e.kind === 'int' || e.kind === 'real')) return e.value;
  return null;
}

const TEST_ATTRS = ['TestMethod', 'Test', 'TestCase', 'TestCaseSource', 'Fact', 'Theory', 'DataTestMethod', 'Property'];
const TEST_CLASS_ATTRS = ['TestClass', 'TestFixture'];

function isTestMethod(m) { return !!attrNamed(m.attrs, TEST_ATTRS); }

function isTestFile(pf) {
  if (pf._isTest !== undefined) return pf._isTest;
  let r = /(^|[/\\])(tests?|[\w.]*\.Tests?|[\w.]*Tests?)[/\\]/i.test(pf.path) || /Tests?\.cs$/.test(pf.path);
  if (!r) {
    for (const td of pf.types) {
      if (attrNamed(td.attrs, TEST_CLASS_ATTRS)) { r = true; break; }
      for (const m of td.members || []) if (m.k === 'Method' && isTestMethod(m)) { r = true; break; }
      if (r) break;
    }
  }
  pf._isTest = r;
  return r;
}

function isGenerated(pf) {
  if (pf._gen !== undefined) return pf._gen;
  let g = /\.(designer|g|g\.i|generated|AssemblyInfo|AssemblyAttributes)\.cs$/i.test(pf.path) || /(^|\/)(obj|bin)\//i.test(pf.path) || /AssemblyInfo\.cs$/i.test(pf.path);
  if (!g && pf.lex) {
    for (const c of pf.lex.comments) {
      if (c.line > 12) break;
      if (/<auto-generated|<autogenerated|generated by a tool|This code was generated/i.test(c.text)) { g = true; break; }
    }
  }
  pf._gen = g;
  return g;
}

function isEventHandler(m) {
  const ps = m.params || [];
  if (ps.length !== 2) return false;
  const t1 = ps[0].type; const t2 = ps[1].type;
  if (!t1 || !t2) return false;
  return (t1.name === 'object' || t1.name === 'Object') && (/EventArgs$|Args$/.test(t2.name) || ps[1].name === 'e' || ps[1].name === 'args');
}

function isOverrideLike(m) {
  return hasMod(m, 'override') || hasMod(m, 'virtual') || hasMod(m, 'abstract') || !!m.iface || hasMod(m, 'extern') || hasMod(m, 'partial') || hasMod(m, 'new');
}

// does the type implement an interface member with this name (when its interfaces are external we cannot know)
function mayImplementInterface(info, name) {
  if (!info) return true;
  for (const i of info.ifaceInfos) if (i.lookup(name)) return true;
  const ext = info.externalBases.filter((b) => /^I[A-Z]/.test(b));
  if (ext.length) return true;
  if (info.baseInfo && mayImplementInterface(info.baseInfo, name)) return true;
  return false;
}

function typeDeclOf(node) { return enclosing(node, ['TypeDecl']); }

function methodOf(node) { return enclosing(node, ['Method', 'Ctor', 'Accessor', 'LocalFunc', 'Lambda', 'Operator', 'Conversion', 'Destructor', 'Property', 'Indexer']); }

function memberOf(node) { return enclosing(node, ['Method', 'Ctor', 'Property', 'Indexer', 'Event', 'Field', 'Operator', 'Conversion', 'Destructor']); }

function isAsyncMember(m) { return !!m && hasMod(m, 'async'); }

function returnsTask(m) {
  const t = m && (m.retType || m.type);
  return !!t && (t.name === 'Task' || t.name === 'ValueTask');
}

function stmtsOf(body) {
  if (!body) return [];
  if (body.k === 'Block') return body.stmts;
  return [body];
}

function isEmptyBlock(b) { return !!b && b.k === 'Block' && b.stmts.length === 0; }

function commentsIn(pf, startLine, endLine) {
  if (!pf.lex) return [];
  return pf.lex.comments.filter((c) => c.line >= startLine && c.line <= endLine);
}

function hasCommentInside(pf, node) {
  return commentsIn(pf, node.line, node.endLine).some((c) => c.line > node.line || c.col > node.col);
}

function identsIn(node) {
  const out = new Set();
  const visit = (n) => {
    if (n.k === 'Name') out.add(n.name);
    if (n.k === 'Member') out.add(n.name);
    forEachChild(n, visit);
  };
  visit(node);
  return out;
}

function containsKind(node, kinds, opts = {}) {
  let found = null;
  const visit = (n) => {
    if (found) return;
    if (kinds.includes(n.k) && n !== node) { found = n; return; }
    if (opts.noLambda && (n.k === 'Lambda' || n.k === 'LocalFunc') && n !== node) return;
    forEachChild(n, visit);
  };
  visit(node);
  return found;
}

function words(name) {
  return String(name).replace(/^_+|^m_/, '').replace(/([a-z0-9])([A-Z])/g, '$1 $2').toLowerCase().split(/[\s_]+/).filter(Boolean);
}

function isPascal(name) { return /^[A-Z][A-Za-z0-9]*$/.test(name) && !/[A-Z]{4,}/.test(name.replace(/[A-Z]{1,3}$/, '')); }
function isCamel(name) { return /^[a-z][A-Za-z0-9]*$/.test(name); }

module.exports = {
  strVal, numVal, isTestMethod, isTestFile, isGenerated, isEventHandler, isOverrideLike, mayImplementInterface, typeDeclOf, methodOf, memberOf,
  isAsyncMember, returnsTask, stmtsOf, isEmptyBlock, commentsIn, hasCommentInside, identsIn, containsKind, words, isPascal, isCamel,
  unparen, dotted, callName, callTarget, hasMod, attrNamed, TEST_ATTRS, TEST_CLASS_ATTRS,
};
