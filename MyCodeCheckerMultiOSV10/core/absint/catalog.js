const POSSIBLE_OK = new Set(['OVERRUN', 'INTEGER_OVERFLOW', 'DIVIDE_BY_ZERO', 'FORWARD_NULL']);
const LOWER = { BLOCKER: 'CRITICAL', CRITICAL: 'MAJOR', MAJOR: 'MINOR', MINOR: 'INFO', INFO: 'INFO' };

const BY_CHECKER = new Map(CHECKERS.map((c) => [c.checker, c]));

function catalog() {
  return CHECKERS.map((c) => ({
    key: `absint:${c.checker}`,
    langs: CPP_ONLY.has(c.checker) ? ['cpp'] : ['c', 'cpp'],
    type: c.type,
    severity: c.severity,
    debtMin: c.type === 'VULNERABILITY' ? 30 : c.severity === 'MINOR' ? 10 : 20,
    tags: ['absint', 'coverity', c.cwe.toLowerCase(), c.cert ? `cert-${c.cert.toLowerCase()}` : '', c.type === 'VULNERABILITY' ? 'security' : ''].filter(Boolean),
    name: c.name,
    why: c.why,
    fix: c.fix,
    category: c.category,
    checker: c.checker,
    cwe: c.cwe,
    cert: c.cert ? `CERT ${c.cert}` : '',
    impact: IMPACT[c.severity],
    domains: c.domains,
    standards: {
      cwe: [c.cwe],
      ...(c.cert ? (/-CPP$/.test(c.cert) ? { certCpp: c.cert } : { certC: c.cert }) : {}),
    },
  }));
}

module.exports = { CHECKERS, BY_CHECKER, POSSIBLE_OK, LOWER, IMPACT, CPP_ONLY, catalog };
