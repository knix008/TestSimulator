export function pt(key, vars) {
  const pair = PAIRS[key];
  let s = pair ? pair[getLanguage() === 'en' ? 1 : 0] : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

