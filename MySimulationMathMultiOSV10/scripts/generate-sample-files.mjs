// npm run generate:sample-files — writes every sample of the start page into
// samples/ as real files, so they can be opened, run and copied like any file:
//
//   samples/README.md                        the list (Korean + English)
//   samples/scripts/<NN_category>/<id>.m     the 샘플 · 예제 scripts (src/lib/samples.js)
//   samples/models/<NN_category>/ex_<id>.smdl the 모델 예제 models (src/lib/modelSamples.js),
//                                            built by the engine from their M code
//   samples/models/<NN_category>/build_ex_<id>.m   that M code (builds the model again)
//   samples/templates/*.m                    the 새로 만들기 templates (function, class, live script)
//
// The files are generated: change the samples in src/lib and run this again
// (test/sample-files.test.mjs checks that samples/ matches them).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SAMPLES, SAMPLE_CATEGORIES, TEMPLATES } from '../src/lib/samples.js';
import { MODEL_SAMPLES, MODEL_CATEGORIES } from '../src/lib/modelSamples.js';
import { createSession } from '../core/session.js';
import { simState } from '../core/sim/state.js';
import { serializeModel } from '../core/sim/model.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'samples');

/** Folder of a category: 01_basics … (the start page order). */
export const folderOf = (cats, id) => `${String(cats.findIndex((c) => c.id === id) + 1).padStart(2, '0')}_${id}`;

/** The header comment of a sample file: names and descriptions in both languages. */
export const headerOf = (s, kind) => [
  `% ${s.name[0]} / ${s.name[1]}`,
  `% ${s.desc[0]}`,
  `% ${s.desc[1]}`,
  `% (${kind} — MySimulationMath start page)`,
  '',
].join('\n');

export const TEMPLATE_FILES = { function: 'myFunction.m', class: 'MyClass.m', live: 'liveScript.m' };

/** Every file of samples/ as { rel: content } (text). */
export function sampleFiles() {
  const files = {};
  for (const s of SAMPLES) files[`scripts/${folderOf(SAMPLE_CATEGORIES, s.cat)}/${s.id}.m`] = headerOf(s, 'script sample') + s.code;
  const session = createSession({ host: { post() {}, request() { return null; } } });
  for (const m of MODEL_SAMPLES) {
    const dir = `models/${folderOf(MODEL_CATEGORIES, m.cat)}`;
    files[`${dir}/build_${m.model}.m`] = headerOf(m, 'example model, builds and opens the model') + m.code;
    const r = session.evaluate(m.code);
    if (!r.ok) throw new Error(`${m.id}: ${r.error && r.error.message}`);
    const model = JSON.parse(JSON.stringify(simState(session.ctx).models.get(m.model).model));
    model.meta = { ...(model.meta || {}), description: `${m.name[0]} / ${m.name[1]} — ${m.desc[0]} / ${m.desc[1]}`, created: '2026-10-30T00:00:00.000Z', modified: '2026-10-30T00:00:00.000Z' };
    // serializeModel stamps "modified" with the current time: fixed here so the files are reproducible
    files[`${dir}/${m.model}.smdl`] = serializeModel(model).replace(/"modified": "[^"]*"/, '"modified": "2026-10-30T00:00:00.000Z"');
  }
  for (const [k, code] of Object.entries(TEMPLATES)) files[`templates/${TEMPLATE_FILES[k] || `${k}.m`}`] = code;
  files['README.md'] = readme();
  return files;
}

function readme() {
  const L = [];
  L.push('# Samples · 샘플', '');
  L.push('시작 화면의 모든 샘플을 파일로 모은 폴더입니다. All the samples of the start page as files.', '');
  L.push('- `scripts/` — 샘플 · 예제 스크립트 (M files): open in the editor and press F5.');
  L.push('- `models/` — 모델 예제 (`.smdl` block-diagram models) and `build_*.m`, the M code that builds each model.');
  L.push('- `templates/` — 새로 만들기 templates (function, class, live script).');
  L.push('', 'Generated by `npm run generate:sample-files` from `src/lib/samples.js` and `src/lib/modelSamples.js`.', '');
  L.push(`## Scripts · 스크립트 (${SAMPLES.length})`, '');
  for (const c of SAMPLE_CATEGORIES) {
    const list = SAMPLES.filter((s) => s.cat === c.id);
    if (!list.length) continue;
    L.push(`### ${c.name[0]} · ${c.name[1]} — \`scripts/${folderOf(SAMPLE_CATEGORIES, c.id)}/\``, '');
    for (const s of list) L.push(`- \`${s.id}.m\` — ${s.name[0]} / ${s.name[1]}: ${s.desc[0]}`);
    L.push('');
  }
  L.push(`## Models · 모델 (${MODEL_SAMPLES.length})`, '');
  for (const c of MODEL_CATEGORIES) {
    const list = MODEL_SAMPLES.filter((m) => m.cat === c.id);
    if (!list.length) continue;
    L.push(`### ${c.name[0]} · ${c.name[1]} — \`models/${folderOf(MODEL_CATEGORIES, c.id)}/\``, '');
    for (const m of list) L.push(`- \`${m.model}.smdl\` — ${m.name[0]} / ${m.name[1]}: ${m.desc[0]}`);
    L.push('');
  }
  L.push('## Templates · 템플릿', '');
  for (const [k, f] of Object.entries(TEMPLATE_FILES)) if (TEMPLATES[k]) L.push(`- \`templates/${f}\` — ${k}`);
  return `${L.join('\n')}\n`;
}

function main() {
  const files = sampleFiles();
  for (const dir of ['scripts', 'models', 'templates']) fs.rmSync(path.join(out, dir), { recursive: true, force: true });
  for (const [rel, text] of Object.entries(files)) {
    const p = path.join(out, rel);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, text);
  }
  const count = (pre) => Object.keys(files).filter((f) => f.startsWith(pre)).length;
  console.log(`samples/: ${count('scripts/')} scripts, ${Object.keys(files).filter((f) => f.endsWith('.smdl')).length} models (+ ${count('models/') / 2} build scripts), ${count('templates/')} templates, README.md`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
