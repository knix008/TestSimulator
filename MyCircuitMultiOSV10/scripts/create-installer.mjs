// Generates the NSIS include that lets the user pick which supported file
// types the installer registers with Windows, plus a JSON copy of the table so
// the application and the installer can be checked against each other.
//
//   npm run build:installer
//
// The table mirrors SUPPORTED_EXTENSIONS in electron/main.cjs and
// "fileAssociations" in package.json. `.mycircuit` is the application's own
// document type: it is built in (registered by electron-builder's
// fileAssociations) and never shown as a choice. Any other entry added here
// appears as a checkbox on an extra "File associations" wizard page; while
// there are none, the page is left out of the installer altogether
// (MYCIRCUIT_ASSOC_COUNT == 0, see build/installer.nsh).
import { writeFileSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dirname, '..')

export const FILE_TYPES = [
  { ext: 'mycircuit', name: 'MyCircuit.Project', ko: 'MyCircuit 프로젝트', en: 'MyCircuit project', role: 'Editor', default: true, builtin: true }
]

const CHOOSABLE = FILE_TYPES.filter((type) => !type.builtin)

// The custom page lives inside the MUI inner dialog, which is 300 x 140
// dialog units. The grid is computed to fit above the two buttons.
const PAGE_WIDTH = 300
const PAGE_HEIGHT = 140
const ROW_HEIGHT = 12
const BUTTON_HEIGHT = 14
const COLUMN_GAP = 6
const ROWS = Math.max(1, Math.floor((PAGE_HEIGHT - BUTTON_HEIGHT - 6) / ROW_HEIGHT))
const COLUMNS = Math.max(1, Math.ceil(CHOOSABLE.length / ROWS))
const COLUMN_WIDTH = Math.floor((PAGE_WIDTH - (COLUMNS - 1) * COLUMN_GAP) / COLUMNS)
if (COLUMNS * ROWS < CHOOSABLE.length) {
  throw new Error(`association page does not fit: ${CHOOSABLE.length} types in ${COLUMNS}x${ROWS}`)
}

const D = (name) => '${' + name + '}' // NSIS ${Macro} without fighting template literals

function nsh() {
  const lines = []
  lines.push('; Generated by scripts/create-installer.mjs - do not edit by hand.')
  lines.push('!include "LogicLib.nsh"')
  lines.push('!include "nsDialogs.nsh"')
  lines.push('!include "WinMessages.nsh"')
  lines.push('')
  lines.push(`!define MYCIRCUIT_ASSOC_COUNT ${CHOOSABLE.length}`)
  // Only the installer has the wizard page; declaring these in the uninstaller
  // pass as well would make makensis warn about unused variables, and
  // electron-builder turns NSIS warnings into errors.
  if (CHOOSABLE.length > 0) {
    lines.push('!ifndef BUILD_UNINSTALLER')
    lines.push('Var AssocDialog')
    lines.push('Var AssocTitle')
    lines.push('Var AssocSubTitle')
    lines.push('Var AssocAllButton')
    lines.push('Var AssocNoneButton')
    CHOOSABLE.forEach((_type, index) => {
      lines.push(`Var AssocBox${index}`)
      lines.push(`Var AssocState${index}`)
    })
    lines.push('!endif')
  }
  lines.push('')

  lines.push('!macro MyCircuitAssocDefaults')
  CHOOSABLE.forEach((type, index) => lines.push(`  StrCpy $AssocState${index} "${type.default ? '1' : '0'}"`))
  lines.push('!macroend')
  lines.push('')

  lines.push('!macro MyCircuitAssocPageCreate')
  if (CHOOSABLE.length > 0) {
    lines.push('  nsDialogs::Create 1018')
    lines.push('  Pop $AssocDialog')
    lines.push(`  ${D('If')} $AssocDialog == error`)
    lines.push('    Abort')
    lines.push(`  ${D('EndIf')}`)
    // The header belongs to the parent window (1037 title, 1038 subtitle).
    lines.push('  GetDlgItem $AssocTitle $HWNDPARENT 1037')
    lines.push('  GetDlgItem $AssocSubTitle $HWNDPARENT 1038')
    lines.push(`  ${D('If')} $LANGUAGE == 1042`)
    lines.push(`    SendMessage $AssocTitle ${D('WM_SETTEXT')} 0 "STR:파일 형식 연결"`)
    lines.push(`    SendMessage $AssocSubTitle ${D('WM_SETTEXT')} 0 "STR:MyCircuit로 열 파일 형식을 선택하세요."`)
    lines.push(`  ${D('Else')}`)
    lines.push(`    SendMessage $AssocTitle ${D('WM_SETTEXT')} 0 "STR:File associations"`)
    lines.push(`    SendMessage $AssocSubTitle ${D('WM_SETTEXT')} 0 "STR:Choose which file types open with MyCircuit."`)
    lines.push(`  ${D('EndIf')}`)
    CHOOSABLE.forEach((type, index) => {
      const x = Math.floor(index / ROWS) * (COLUMN_WIDTH + COLUMN_GAP)
      const y = (index % ROWS) * ROW_HEIGHT
      lines.push(`  ${D('NSD_CreateCheckbox')} ${x}u ${y}u ${COLUMN_WIDTH}u ${ROW_HEIGHT}u ""`)
      lines.push(`  Pop $AssocBox${index}`)
      lines.push(`  ${D('If')} $LANGUAGE == 1042`)
      lines.push(`    ${D('NSD_SetText')} $AssocBox${index} ".${type.ext} — ${type.ko}"`)
      lines.push(`  ${D('Else')}`)
      lines.push(`    ${D('NSD_SetText')} $AssocBox${index} ".${type.ext} — ${type.en}"`)
      lines.push(`  ${D('EndIf')}`)
      lines.push(`  ${D('If')} $AssocState${index} == "1"`)
      lines.push(`    ${D('NSD_Check')} $AssocBox${index}`)
      lines.push(`  ${D('EndIf')}`)
    })
    const buttonRow = ROWS * ROW_HEIGHT + 4
    lines.push(`  ${D('NSD_CreateButton')} 0u ${buttonRow}u 80u 14u ""`)
    lines.push('  Pop $AssocAllButton')
    lines.push(`  ${D('NSD_CreateButton')} 86u ${buttonRow}u 80u 14u ""`)
    lines.push('  Pop $AssocNoneButton')
    lines.push(`  ${D('If')} $LANGUAGE == 1042`)
    lines.push(`    ${D('NSD_SetText')} $AssocAllButton "전체 선택"`)
    lines.push(`    ${D('NSD_SetText')} $AssocNoneButton "전체 해제"`)
    lines.push(`  ${D('Else')}`)
    lines.push(`    ${D('NSD_SetText')} $AssocAllButton "Select all"`)
    lines.push(`    ${D('NSD_SetText')} $AssocNoneButton "Clear all"`)
    lines.push(`  ${D('EndIf')}`)
    lines.push(`  ${D('NSD_OnClick')} $AssocAllButton MyCircuitAssocSelectAll`)
    lines.push(`  ${D('NSD_OnClick')} $AssocNoneButton MyCircuitAssocSelectNone`)
    lines.push('  nsDialogs::Show')
  }
  lines.push('!macroend')
  lines.push('')

  lines.push('!macro MyCircuitAssocCheckAll')
  CHOOSABLE.forEach((_type, index) => lines.push(`  ${D('NSD_Check')} $AssocBox${index}`))
  lines.push('!macroend')
  lines.push('')
  lines.push('!macro MyCircuitAssocUncheckAll')
  CHOOSABLE.forEach((_type, index) => lines.push(`  ${D('NSD_Uncheck')} $AssocBox${index}`))
  lines.push('!macroend')
  lines.push('')

  lines.push('!macro MyCircuitAssocPageLeave')
  CHOOSABLE.forEach((_type, index) => lines.push(`  ${D('NSD_GetState')} $AssocBox${index} $AssocState${index}`))
  lines.push('!macroend')
  lines.push('')

  // Registry writes for the checked types.
  lines.push('!macro MyCircuitWriteAssociations')
  CHOOSABLE.forEach((type, index) => {
    const progId = type.name
    lines.push(`  ${D('If')} $AssocState${index} != "0"`)
    lines.push(`    WriteRegStr SHCTX "Software\\Classes\\${progId}" "" "${type.en}"`)
    lines.push(`    WriteRegStr SHCTX "Software\\Classes\\${progId}\\DefaultIcon" "" "$INSTDIR\\resources\\file-icon.ico"`)
    lines.push(`    WriteRegStr SHCTX "Software\\Classes\\${progId}\\shell\\open\\command" "" '"$INSTDIR\\${D('APP_EXECUTABLE_FILENAME')}" "%1"'`)
    lines.push(`    WriteRegStr SHCTX "Software\\Classes\\.${type.ext}\\OpenWithProgids" "${progId}" ""`)
    if (type.role === 'Editor') lines.push(`    WriteRegStr SHCTX "Software\\Classes\\.${type.ext}" "" "${progId}"`)
    lines.push(`  ${D('EndIf')}`)
  })
  lines.push("  System::Call 'shell32::SHChangeNotify(i 0x08000000, i 0, i 0, i 0)'")
  lines.push('!macroend')
  lines.push('')

  // Remove every association we may have written.
  lines.push('!macro MyCircuitDeleteAssociations')
  CHOOSABLE.forEach((type) => {
    lines.push(`  DeleteRegKey SHCTX "Software\\Classes\\${type.name}"`)
    lines.push(`  DeleteRegValue SHCTX "Software\\Classes\\.${type.ext}\\OpenWithProgids" "${type.name}"`)
    lines.push(`  ReadRegStr $0 SHCTX "Software\\Classes\\.${type.ext}" ""`)
    lines.push(`  ${D('If')} $0 == "${type.name}"`)
    lines.push(`    DeleteRegValue SHCTX "Software\\Classes\\.${type.ext}" ""`)
    lines.push(`  ${D('EndIf')}`)
  })
  lines.push("  System::Call 'shell32::SHChangeNotify(i 0x08000000, i 0, i 0, i 0)'")
  lines.push('!macroend')
  lines.push('')
  return lines.join('\n')
}

mkdirSync(join(root, 'build'), { recursive: true })
writeFileSync(join(root, 'build', 'installer-associations.nsh'), `${nsh()}\n`, 'utf8')
writeFileSync(
  join(root, 'build', 'file-types.json'),
  `${JSON.stringify({ generator: 'scripts/create-installer.mjs', types: FILE_TYPES }, null, 2)}\n`,
  'utf8'
)
const builtin = FILE_TYPES.length - CHOOSABLE.length
console.log(`installer associations written: ${CHOOSABLE.length} selectable + ${builtin} built-in file type(s)${CHOOSABLE.length ? `, ${COLUMNS} x ${ROWS} on the page` : ' (association page omitted)'}`)
