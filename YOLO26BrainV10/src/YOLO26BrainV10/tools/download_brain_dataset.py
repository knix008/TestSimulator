# -*- coding: utf-8 -*-
"""Download Ultralytics brain-tumor dataset into data/brain_ct_seg for YOLO26BrainV10.

This script prepares segmentation-style labels by converting detection boxes
(`class xc yc w h`) into rectangle polygons.

Usage:
  python download_brain_dataset.py
  python download_brain_dataset.py --force
  python download_brain_dataset.py --repo D:/path/to/YOLO26BrainV10
"""

from __future__ import annotations

import argparse
import shutil
import tempfile
import time
import urllib.request
import zipfile
from pathlib import Path


BRAIN_TUMOR_ZIP_URL = "https://github.com/ultralytics/assets/releases/download/v0.0.0/brain-tumor.zip"
TRAIN_IMG_EXT = frozenset({".png", ".jpg", ".jpeg", ".bmp", ".tif", ".tiff", ".webp"})


def find_repo_root(start: Path) -> Path:
    cur = start.resolve()
    for path in [cur, *cur.parents]:
        if (path / "YOLO26BrainV10.sln").is_file() or (path / "YOLO26BrainV10.slnx").is_file():
            return path
    raise FileNotFoundError(
        f"Could not find YOLO26BrainV10.sln or YOLO26BrainV10.slnx from: {start}"
    )


def dataset_root(repo: Path) -> Path:
    return repo / "data" / "brain_ct_seg"


def ensure_layout(repo: Path) -> None:
    ds = dataset_root(repo)
    for part in ("images/train", "images/val", "labels/train", "labels/val"):
        (ds / part).mkdir(parents=True, exist_ok=True)


def write_data_yaml(repo: Path) -> None:
    yml = dataset_root(repo) / "data.yaml"
    root = dataset_root(repo).resolve().as_posix()
    text = (
        "# Generated by tools/download_brain_dataset.py\n"
        f"path: {root}\n"
        "train: images/train\n"
        "val: images/val\n"
        "names:\n"
        "  0: negative\n"
        "  1: positive\n"
    )
    yml.write_text(text, encoding="utf-8")


def count_train_images(repo: Path) -> int:
    d = dataset_root(repo) / "images" / "train"
    if not d.is_dir():
        return 0
    return sum(1 for f in d.iterdir() if f.is_file() and f.suffix.lower() in TRAIN_IMG_EXT)


def clear_dataset_media(repo: Path) -> None:
    ds = dataset_root(repo)
    for split in ("train", "val"):
        for kind in ("images", "labels"):
            d = ds / kind / split
            if not d.is_dir():
                continue
            for f in d.iterdir():
                if f.is_file():
                    f.unlink()


def clip01(x: float) -> float:
    return max(0.0, min(1.0, x))


def det_line_to_seg(parts: list[str]) -> str | None:
    if len(parts) != 5:
        return None
    try:
        c = int(float(parts[0]))
        xc, yc, w, h = (float(parts[1]), float(parts[2]), float(parts[3]), float(parts[4]))
    except ValueError:
        return None

    x1 = clip01(xc - w / 2)
    x2 = clip01(xc + w / 2)
    y1 = clip01(yc - h / 2)
    y2 = clip01(yc + h / 2)
    return f"{c} {x1:.6f} {y1:.6f} {x2:.6f} {y1:.6f} {x2:.6f} {y2:.6f} {x1:.6f} {y2:.6f}"


def convert_label_text_to_seg(raw: str) -> str:
    out: list[str] = []
    for line in raw.splitlines():
        line = line.strip()
        if not line:
            continue
        parts = line.split()
        seg = det_line_to_seg(parts)
        out.append(seg if seg is not None else line)
    return "\n".join(out) + ("\n" if out else "")


def download_url_to_file(url: str, dest: Path, retries: int = 3) -> None:
    req = urllib.request.Request(
        url,
        headers={"User-Agent": "YOLO26BrainV10-download-brain-dataset/1.0"},
    )
    last_err: Exception | None = None
    for i in range(1, retries + 1):
        try:
            with urllib.request.urlopen(req, timeout=600) as resp:  # noqa: S310 (fixed trusted URL)
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_bytes(resp.read())
            return
        except Exception as e:  # noqa: BLE001
            last_err = e
            if i >= retries:
                break
            wait_s = min(2**i, 10)
            print(f"Retry {i}/{retries} failed: {e} -> waiting {wait_s}s")
            time.sleep(wait_s)
    raise RuntimeError(f"Failed to download {url}") from last_err


def find_dataset_root(unpacked: Path) -> Path:
    for train_img_dir in unpacked.rglob("images/train"):
        if not train_img_dir.is_dir():
            continue
        root = train_img_dir.parent.parent
        if (root / "labels" / "train").is_dir():
            return root.resolve()
    raise FileNotFoundError("Could not locate dataset root with images/train and labels/train")


def fetch(repo: Path, force: bool) -> int:
    if not force and count_train_images(repo) > 0:
        print(
            "Training images already exist. Re-run with --force to clear and re-download.",
        )
        return 1

    ensure_layout(repo)
    write_data_yaml(repo)
    if force:
        clear_dataset_media(repo)

    print("Downloading Ultralytics brain-tumor.zip (~4.2MB, AGPL-3.0)...")
    with tempfile.TemporaryDirectory() as td:
        zpath = Path(td) / "brain-tumor.zip"
        download_url_to_file(BRAIN_TUMOR_ZIP_URL, zpath)
        unpack = Path(td) / "unpacked"
        unpack.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(zpath, "r") as zf:
            zf.extractall(unpack)

        src_root = find_dataset_root(unpack)
        ds = dataset_root(repo)
        n_img = 0
        n_lbl_nonempty = 0
        for split in ("train", "val"):
            simages = src_root / "images" / split
            slabels = src_root / "labels" / split
            if not simages.is_dir():
                continue
            dimages = ds / "images" / split
            dlabels = ds / "labels" / split
            for img in sorted(simages.iterdir()):
                if not img.is_file() or img.suffix.lower() not in TRAIN_IMG_EXT:
                    continue
                shutil.copy2(img, dimages / img.name)
                n_img += 1

                sf = slabels / f"{img.stem}.txt"
                df = dlabels / f"{img.stem}.txt"
                if sf.is_file():
                    raw = sf.read_text(encoding="utf-8", errors="replace")
                    conv = convert_label_text_to_seg(raw)
                    df.write_text(conv, encoding="utf-8")
                    if conv.strip():
                        n_lbl_nonempty += 1
                else:
                    df.write_text("", encoding="utf-8")

    print(
        f"Done. Copied {n_img} images to data/brain_ct_seg and generated {n_lbl_nonempty} non-empty segmentation labels."
    )
    print(
        "Note: source labels are detection boxes. Converted labels are rectangle polygons for segmentation pipeline bootstrap."
    )
    return 0


def main() -> int:
    p = argparse.ArgumentParser(
        description="Download Ultralytics brain-tumor dataset into data/brain_ct_seg for YOLO26BrainV10.",
    )
    p.add_argument(
        "--repo",
        type=Path,
        default=None,
        help="Repository root containing YOLO26BrainV10.sln (default: auto-detect from script location).",
    )
    p.add_argument(
        "--force",
        action="store_true",
        help="Clear existing train/val images and labels under data/brain_ct_seg before download.",
    )
    args = p.parse_args()

    repo = args.repo.expanduser().resolve() if args.repo else find_repo_root(Path(__file__).resolve().parent)
    return fetch(repo, force=args.force)


if __name__ == "__main__":
    raise SystemExit(main())
