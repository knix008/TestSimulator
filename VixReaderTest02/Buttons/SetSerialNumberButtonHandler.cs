        // 시리얼 번호 형식을 생성하는 메서드
        private string GenerateSerialNumberFormat()
        {
            string deviceType = CurrentDeviceType;
            int currentYear = DateTime.Now.Year;
            int yearSuffix = currentYear % 10; // 2025 -> 5
            int weekOfYear = GetWeekOfYear(DateTime.Now);
            
            return $"{deviceType}{yearSuffix}{weekOfYear:D2}"; // 예: M501
        }

        // 연도의 주차를 계산하는 메서드
        private int GetWeekOfYear(DateTime date)
        {
            var culture = System.Globalization.CultureInfo.CurrentCulture;
            var calendar = culture.Calendar;
            var calendarWeekRule = culture.DateTimeFormat.CalendarWeekRule;
            var firstDayOfWeek = culture.DateTimeFormat.FirstDayOfWeek;
    
            return calendar.GetWeekOfYear(date, calendarWeekRule, firstDayOfWeek);
        }

        // 4자리 제품 번호를 검증하는 메서드 (기존 3자리에서 4자리로 변경)
        private bool ValidateProductNumber(string productNumber)
        {
            if (string.IsNullOrWhiteSpace(productNumber))
            {
                Logger.LogMessage(LogTextBox, "❌ 제품 번호가 입력되지 않았습니다.");
                return false;
            }

            // 숫자만 포함되어야 함
            if (!productNumber.All(char.IsDigit))
            {
                Logger.LogMessage(LogTextBox, "❌ 제품 번호는 숫자만 포함해야 합니다.");
                return false;
            }

            // 1-4자리 숫자여야 함 (0001로 패딩될 것임)
            if (productNumber.Length < 1 || productNumber.Length > 4)
            {
                Logger.LogMessage(LogTextBox, "❌ 제품 번호는 1-4자리 숫자여야 합니다.");
                return false;
            }

            // 숫자 범위 검증 (1-9999)
            if (int.TryParse(productNumber, out int number))
            {
                if (number < 1 || number > 9999)
                {
                    Logger.LogMessage(LogTextBox, "❌ 제품 번호는 1-9999 범위의 숫자여야 합니다.");
                    return false;
                }
            }
            else
            {
                Logger.LogMessage(LogTextBox, "❌ 유효하지 않은 숫자 형식입니다.");
                return false;
            }

            return true;
        }
