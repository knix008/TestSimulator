        // 시리얼 번호 전체 형식 검증 메서드 추가
        private bool IsValidSerialNumberFormat(string serial, string deviceType)
        {
            // deviceType은 "M" 또는 "G"만 허용
            if (string.IsNullOrEmpty(serial) || serial.Length != 8)
                return false;
            if (!(deviceType == "M" || deviceType == "G"))
                return false;
            if (!serial.StartsWith(deviceType, StringComparison.OrdinalIgnoreCase))
                return false;
            // M/G + 3자리 숫자 + 4자리 숫자
            string numberPart = serial.Substring(1, 3);
            string productPart = serial.Substring(4, 4);
            return numberPart.All(char.IsDigit) && productPart.All(char.IsDigit);
        }

        // 🔧 다음 제품 번호를 자동으로 계산하는 메서드 추가
        private string GetNextProductNumber(string currentPrefix)
        {
            try
            {
                // 이전에 설정한 시리얼 번호가 없으면 0001 반환
                if (string.IsNullOrEmpty(_lastSetSerialNumber))
                {
                    Logger.LogMessage(LogTextBox, "📋 이전 설정 기록이 없어 기본값 0001을 제안합니다.");
                    return "0001";
                }

                // 이전 시리얼 번호에서 접두사와 제품 번호 분리
                if (_lastSetSerialNumber.Length >= 4)
                {
                    string lastPrefix = _lastSetSerialNumber.Substring(0, _lastSetSerialNumber.Length - 4);
                    string lastProductNumber = _lastSetSerialNumber.Substring(_lastSetSerialNumber.Length - 4);

                    // 접두사가 같으면 제품 번호를 1 증가
                    if (lastPrefix == currentPrefix)
                    {
                        if (int.TryParse(lastProductNumber, out int lastNumber))
                        {
                            int nextNumber = lastNumber + 1;
                            
                            // 9999를 초과하면 0001로 순환
                            if (nextNumber > 9999)
                            {
                                Logger.LogMessage(LogTextBox, "⚠️ 제품 번호가 9999를 초과하여 0001로 순환합니다.");
                                nextNumber = 1;
                            }
                            
                            string nextProductNumber = nextNumber.ToString("D4");
                            Logger.LogMessage(LogTextBox, $"📈 이전 번호 {lastProductNumber}에서 자동 증가: {nextProductNumber}");
                            return nextProductNumber;
                        }
                    }
                    else
                    {
                        Logger.LogMessage(LogTextBox, "📋 접두사가 변경되어 기본값 0001을 제안합니다.");
                        Logger.LogMessage(LogTextBox, $"   이전 접두사: {lastPrefix} → 현재 접두사: {currentPrefix}");
                    }
                }

                // 파싱 실패 시 기본값 반환
                Logger.LogMessage(LogTextBox, "📋 이전 번호 분석 실패로 기본값 0001을 제안합니다.");
                return "0001";
            }
            catch (Exception ex)
            {
                Logger.LogMessage(LogTextBox, $"⚠️ 다음 번호 계산 중 오류: {ex.Message}. 기본값 0001을 사용합니다.");
                return "0001";
            }
        }

