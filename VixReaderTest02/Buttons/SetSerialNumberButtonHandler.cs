        private async void SetSerialNumber_Click(object sender, EventArgs e)
        {
            try
            {
                // 현재 디바이스 타입에 맞는 시리얼 번호 자동 생성 정보
                string autoGeneratedPrefix = GenerateSerialNumberFormat();
                
                // 🔧 다음 시리얼 번호 자동 증가 계산
                string suggestedProductNumber = GetNextProductNumber(autoGeneratedPrefix);
                
