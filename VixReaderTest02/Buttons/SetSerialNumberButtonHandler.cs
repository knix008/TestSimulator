                    return;
                }

                // 완전한 시리얼 번호 생성
                string fullSerialNumber = autoGeneratedPrefix + productNumber.PadLeft(4, '0');

                Logger.LogMessage(LogTextBox, "🔢 시리얼 번호 자동 생성 시작");
                Logger.LogMessage(LogTextBox, $"📋 자동 생성된 접두사: {autoGeneratedPrefix}");
                Logger.LogMessage(LogTextBox, $"📋 타입: {CurrentDeviceType}, 년도: {DateTime.Now.Year}, 주차: {GetWeekOfYear(DateTime.Now):D2}");
                Logger.LogMessage(LogTextBox, $"📋 입력된 제품 번호: {productNumber.PadLeft(4, '0')}");
                Logger.LogMessage(LogTextBox, $"🏷️  생성된 완전한 시리얼 번호: {fullSerialNumber}");

