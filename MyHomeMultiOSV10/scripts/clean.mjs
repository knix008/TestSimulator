// Removes everything a build or a test run produces, so the next build starts from scratch.
//
//   npm run clean            build output, test results, caches and the installers (release/ and the
//                            copies in the project root)
//   npm run clean:all        the above + node_modules/ (full reset; run `npm install` afterwards)
//   npm run clean:dry        list what `clean:all` would remove, delete nothing
//   npm run clean -- --dry-run   the same for `clean`
//
// Everything listed here is git-ignored (.gitignore) and made again by `npm install`, `npm run build:*`
// or `npm test`. Nothing tracked by git is touched — public/docs/ (made by build:docs but committed) and
// doc/video/ stay.
//
// Usage: node scripts/clean.mjs [--all] [--dry-run]
import { existsSync, readdirSync, rmSync, statSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const all = args.includes('--all');
const dryRun = args.includes('--dry-run') || args.includes('-n');

const targets = [
  ['dist', 'web bundle (vite build)'],
  ['src-tauri/target', 'Rust build output and installers (cargo / tauri build)'],
  ['src-tauri/target-test', 'Rust build output of the test runs (npm test)'],
  ['src-tauri/gen', 'Tauri schemas generated by tauri-build'],
  ['release', 'installers and the web package (npm run build:*)'],
  ['test-results', 'test reports (npm test)'],
  ['node_modules/.vite', 'Vite dependency cache'],
];

// Installers and the web package copied to the project root (.gitignore: /MyHomeMaker-*.exe …) and log files.
const rootFiles = /^MyHomeMaker-.*\.(exe|msi|dmg|deb|rpm|AppImage|zip)$|\.log$/i;
for (const name of readdirSync(rootDir)) {
  if (rootFiles.test(name)) targets.push([name, name.endsWith('.log') ? 'log file' : 'installer copied to the project root']);
}

if (all) targets.push(['node_modules', 'installed dependencies']);

function sizeOf(path) {
  try {
    const st = statSync(path);
    if (!st.isDirectory()) return st.size;
    let total = 0;
    for (const entry of readdirSync(path, { withFileTypes: true })) {
      if (entry.isSymbolicLink()) continue;
      total += sizeOf(join(path, entry.name));
    }
    return total;
  } catch {
    return 0; // unreadable entries just do not count towards the total
  }
}

const mb = (bytes) => `${(bytes / 1024 / 1024).toFixed(1)} MB`;

let removed = 0;
let freed = 0;
let failed = 0;

for (const [rel, why] of targets) {
  const path = resolve(rootDir, rel);
  // Never step outside the project, whatever ends up in the list.
  if (path === rootDir || !path.startsWith(rootDir + sep)) continue;
  if (!existsSync(path)) continue;

  const bytes = sizeOf(path);
  const label = `${relative(rootDir, path).split(sep).join('/')}  (${why}, ${mb(bytes)})`;

  if (dryRun) {
    console.log(`[clean] would remove ${label}`);
    removed++;
    freed += bytes;
    continue;
  }
  try {
    rmSync(path, { recursive: true, force: true, maxRetries: 3, retryDelay: 200 });
    console.log(`[clean] removed ${label}`);
    removed++;
    freed += bytes;
  } catch (err) {
    // On Windows a running app (npm start keeps src-tauri/target/debug/*.exe open) or an Explorer window holds a handle.
    console.error(`[clean] could not remove ${label}: ${err.message}`);
    failed++;
  }
}

if (!removed && !failed) {
  console.log('[clean] Nothing to remove - already clean.');
} else {
  console.log(dryRun
    ? `[clean] ${removed} item(s), ${mb(freed)} would be removed. Run without --dry-run to delete.`
    : `[clean] ${removed} item(s) removed, ${mb(freed)} freed.`);
  if (!all && !dryRun) console.log('[clean] node_modules/ kept - use "npm run clean:all" to remove it too.');
}

if (failed) {
  console.error(`[clean] ${failed} item(s) could not be removed - close MyHomeMaker (npm start) or Explorer windows using them and retry.`);
  process.exit(1);
}
