// Material presets for the "hard" and miscellaneous categories: metal, glass, ceramic, plant and other.
// Merged into MATERIAL_PRESETS (materials.js). Same shape as there:
//   { id, category, ko, en, color, roughness, metalness, repeat, ...extra }
//
// Physical rules used here:
// - Metals: metalness 1, colour = the metal's reflectance tint, roughness by finish
//   (mirror/polished 0.03–0.08, satin 0.2, brushed 0.3, bead-blasted/raw 0.45–0.6).
//   Paints and powder coats on metal are dielectric (metalness 0); metallic car-style paints sit between.
// - Glass: clear, frosted and patterned glass (where light really passes and refracts) uses `transmission`
//   (three.js renders an extra transmission pass while any is on screen). Tinted, coloured, stained and
//   laminated-colour glass uses cheap alpha blending (`transparent` + `opacity`) — it reads the same as
//   a decorative surface and costs nothing extra. Back-painted glass is opaque with a clear coat; mirrors
//   are metalness 1.
// - Ceramics: glazes are a clear coat over the body colour; unglazed bodies are rough and dielectric.
// - Lights, neon and screens use `emissive`.
// `repeat` = metres per texture tile; `textures` = a Poly Haven set (scripts/fetch-assets.mjs);
// `textureSize` overrides the set's real-world size (metres per tile).

const P = (id, category, ko, en, color, roughness, metalness = 0, extra = {}) => ({ id, category, ko, en, color, roughness, metalness, repeat: 1, ...extra });

// Procedural patterns (engine/patterns.js); the pattern carries the colours, the preset colour is their average.
/** Perforated sheet: round holes (dark) on a staggered grid. */
const perforated = (sheet, spacing = 0.012, r = 0.0035, hole = '#151515') => ({ kind: 'dots', base: sheet, colors: [hole], spacing, r, bump: 0.4 });
/** Square wire mesh: thin wires (grout) around dark openings. */
const wireMesh = (wire, opening = 0.008, wireWidth = 0.0012, hole = '#161616') => ({ kind: 'grid', w: opening + wireWidth, colors: [hole], grout: wire, groutWidth: wireWidth, bump: 0.4 });
/** Hammered / planished metal: soft dimples. */
const hammered = (base) => ({ kind: 'plain', base, size: 0.3, cloud: 0.45, cloudScale: 0.025, bump: 1.5 });
/** Flat colour from a pattern, so a texture set only lends its relief (normal/roughness), not its paint. */
const reliefOnly = (base) => ({ kind: 'plain', base, size: 0.5 });
/** Expanded metal: diamond openings between strands. */
const expanded = (strand, hole = '#121212', w = 0.032, h = 0.014, strandWidth = 0.0022) => ({ kind: 'diamond', w, h, colors: [hole], grout: strand, groutWidth: strandWidth, bump: 0.5 });
/** Brushed lines along x. */
const brushed = (base) => ({ kind: 'plain', base, size: 0.25, grain: 0.18, streak: 'x', bump: 0.3 });
/** Glass ribs: alternating light/dark stripes, raised and sunk (bump), for reeded/fluted glass. */
const ribs = (glass, width, dir = 'v', groove = 0.002) => ({ kind: 'stripes', widths: [width, groove], colors: [glass, '#dfe7e5'], heights: [1, 0.2], dir, bump: 2 });
/** Crackle glaze: fine dark lines in the glaze. */
const crackle = (glaze, line) => ({ kind: 'marble', base: glaze, veins: [[line, 0.0007, 60, 0.55], [line, 0.0004, 90, 0.35]], angle: 0, size: 0.4, bump: 0.2 });
/** Speckled glaze / clay: iron spots. */
const speckled = (base, dark = '#4a3a2c', density = 0.06) => ({ kind: 'plain', base, size: 0.3, cloud: 0.12, speckle: [[dark, density, 0.0015], [dark, density / 3, 0.003]], bump: 0.3 });

