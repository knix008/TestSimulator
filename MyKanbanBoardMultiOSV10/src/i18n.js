export const DICTIONARIES = { ko, en };
let language = 'ko';

export function setLanguage(next) {
  language = next === 'en' ? 'en' : 'ko';
  if (globalThis.document) globalThis.document.documentElement.lang = language;
}

export const getLanguage = () => language;

export function t(key, params = {}) {
  const text = DICTIONARIES[language][key] ?? DICTIONARIES.ko[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

/** File size for progress text. */
export function formatBytes(bytes) {
  const units = ['B', 'KB', 'MB', 'GB', 'TB'];
  let value = Number(bytes) || 0;
  let unit = 0;
  while (value >= 1024 && unit < units.length - 1) {
    value /= 1024;
    unit += 1;
  }
  return `${unit ? value.toFixed(value < 10 ? 1 : 0) : value} ${units[unit]}`;
}
