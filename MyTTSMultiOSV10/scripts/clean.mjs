// Removes everything a build or a test run produces, so the next build starts from scratch.
//
//   npm run clean            build output (dist/, src-tauri/target, src-tauri/gen) and the
//                            installers copied to the project root
//   npm run clean:all        the above + node_modules/ and the test leftovers in %TEMP%: the
//                            copy of the voice models the tests use (tts-multios-test-data) and
//                            scratch folders of interrupted runs (tts-test-*, tts-desktop-* …)
//   npm run clean:dry        list what clean:all would remove, delete nothing
//   (any of them + --dry-run lists only)
//
// Never touched: sources, doc/ (including doc/images, made by npm run guide:images) and the
// program's real data in %APPDATA%\TTSMultiOSV10 (downloaded models, logs).
//
// Usage: node scripts/clean.mjs [--all] [--dry-run]
import { existsSync, readdirSync, rmSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = resolve(join(dirname(fileURLToPath(import.meta.url)), '..'));
const tempDir = resolve(tmpdir());
const args = process.argv.slice(2);
const all = args.includes('--all');
const dryRun = args.includes('--dry-run') || args.includes('-n');

// [path, why, base it must stay inside]
const targets = [
  [join(rootDir, 'dist'), 'web pages and Node sidecar (build-tauri-web)', rootDir],
  [join(rootDir, 'src-tauri', 'target'), 'Rust build output, programs and installers (cargo / tauri build)', rootDir],
  [join(rootDir, 'src-tauri', 'gen'), 'Tauri schemas generated by tauri-build', rootDir],
];

// Installers that build:* copies from src-tauri/target to the project root.
for (const name of readdirSync(rootDir)) {
  if (/^(MyTTS|TTS[ _-]Multi[ _-]OS)[ _-].*\.(exe|msi|dmg|AppImage|deb|rpm)$/i.test(name)) targets.push([join(rootDir, name), 'installer copied to the project root', rootDir]);
}

if (all) {
  targets.push([join(rootDir, 'node_modules'), 'installed dependencies (npm install brings them back)', rootDir]);
  // Test leftovers in %TEMP%: only names the test scripts create (scripts/lib/testdata.mjs, cdp.mjs, test/*.mjs).
  targets.push([join(tempDir, 'tts-multios-test-data'), 'copy of the voice models used by the tests (copied again on the next npm test)', tempDir]);
  for (const name of existsSync(tempDir) ? readdirSync(tempDir) : []) {
    if (/^tts-(test|test-edge|desktop|unit|unit-crash|shots|dbg|clip)-[A-Za-z0-9]{6}$/.test(name)) targets.push([join(tempDir, name), 'scratch folder of an interrupted test run', tempDir]);
  }
}

function sizeOf(path) {
  try {
    const st = statSync(path);
    if (!st.isDirectory()) return st.size;
    let total = 0;
    for (const entry of readdirSync(path, { withFileTypes: true })) {
      if (entry.isSymbolicLink()) continue;
      total += sizeOf(join(path, entry.name));
    }
    return total;
  } catch {
    return 0; // unreadable entries just do not count towards the total
  }
}
const mb = (bytes) => `${(bytes / 1024 / 1024).toFixed(1)} MB`;
const shown = (path) => (path.startsWith(rootDir + sep) ? relative(rootDir, path) : path).split(sep).join('/');

let removed = 0;
let freed = 0;
let failed = 0;
for (const [target, why, base] of targets) {
  const path = resolve(target);
  // Never step outside the allowed folder, whatever ends up in the list.
  if (!path.startsWith(base + sep)) continue;
  if (process.env.APPDATA && path.toLowerCase().startsWith(resolve(process.env.APPDATA).toLowerCase() + sep)) continue;
  if (!existsSync(path)) continue;
  const bytes = sizeOf(path);
  const label = `${shown(path)}  (${why}, ${mb(bytes)})`;
  if (dryRun) {
    console.log(`[clean] would remove ${label}`);
    removed += 1;
    freed += bytes;
    continue;
  }
  try {
    rmSync(path, { recursive: true, force: true, maxRetries: 3, retryDelay: 200 });
    console.log(`[clean] removed ${label}`);
    removed += 1;
    freed += bytes;
  } catch (error) {
    // On Windows a running program, its Node host or an Explorer window keeps files open.
    console.error(`[clean] could not remove ${label}: ${error.message}`);
    failed += 1;
  }
}

if (!removed && !failed) {
  console.log('[clean] Nothing to remove - already clean.');
} else {
  console.log(dryRun
    ? `[clean] ${removed} item(s), ${mb(freed)} would be removed. Run without --dry-run to delete.`
    : `[clean] ${removed} item(s) removed, ${mb(freed)} freed.`);
  if (!all && !dryRun) console.log('[clean] node_modules/ and the test model copy kept - use "npm run clean:all" to remove them too.');
}
if (failed) {
  console.error(`[clean] ${failed} item(s) could not be removed - close MyTTS (and Explorer windows on these folders) and retry.`);
  process.exit(1);
}
