const stored = (typeof localStorage !== 'undefined' && localStorage.getItem('mypdfviewer-lang')) || null;
const fallback = (typeof navigator !== 'undefined' && navigator.language) || 'en';
const initial = stored || (fallback.startsWith('ko') ? 'ko' : 'en');

i18n.use(initReactI18next).init({
  resources: { ko: { translation: ko }, en: { translation: en } },
  lng: initial,
  fallbackLng: 'en',
  interpolation: { escapeValue: false },
});

export function setLanguage(lng) {
  try { localStorage.setItem('mypdfviewer-lang', lng); } catch { /* ignore */ }
  return i18n.changeLanguage(lng);
}

