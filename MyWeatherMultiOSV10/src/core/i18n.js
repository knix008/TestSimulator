export const DICT = { ko: {}, en: {} };
for (const [key, ko, en] of ROWS) {
  DICT.ko[key] = ko;
  DICT.en[key] = en;
}

export function dictionaryKeys() {
  return Object.keys(DICT.ko);
}

export function createI18n(language = "ko") {
  const missing = new Set();
  const api = {
    language: language === "en" ? "en" : "ko",
    missing,
    t(key) {
      const table = DICT[api.language];
      if (!Object.prototype.hasOwnProperty.call(table, key)) {
        missing.add(key);
        return `«${key}»`;
      }
      return table[key];
    },
    setLanguage(next) {
      api.language = next === "en" ? "en" : "ko";
    },
  };
  return api;
}

export function formatMessage(text, vars = {}) {
  return String(text).replace(/\{(\w+)\}/g, (_, key) => (vars[key] == null ? "" : String(vars[key])));
}
