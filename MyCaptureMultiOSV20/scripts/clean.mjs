// Removes everything a build or a test run produces, so the next one starts from scratch.
//
//   npm run clean                build output, Rust target, installers, test results
//   npm run clean:all            the above + node_modules/ (full reset; run
//                                `npm install` before the next start or build)
//   npm run clean -- --dry-run   list what would be removed, delete nothing
//
// Everything listed here is git-ignored (.gitignore) and comes back with
// `npm install`, `npm start`, `npm test` or `npm run build:*`. Sources, doc/
// (including doc/images, made by `npm run guide:images`) and assets/ are never touched.
//
// Usage: node scripts/clean.mjs [--all] [--dry-run]
import { existsSync, readdirSync, rmSync, statSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const all = args.includes('--all');
const dryRun = args.includes('--dry-run') || args.includes('-n');

const targets = [
  ['dist', 'web bundle (vite build)'],
  ['src-tauri/target', 'Rust build output and installers (cargo / tauri build)'],
  ['src-tauri/gen', 'Tauri schemas generated by tauri-build'],
  ['release', 'installers collected by build:*'],
  ['test-results', 'npm test results'],
  ['node_modules/.vite', 'Vite dependency cache'],
];

// Installers copied to the project root (MyCapture-Setup-1.0.2.exe …), by name.
const installer = /^MyCapture[-_].*\.(exe|msi|dmg|deb|rpm|AppImage)$/i;
for (const name of readdirSync(rootDir)) {
  if (!installer.test(name)) continue;
  try { if (!statSync(join(rootDir, name)).isFile()) continue; } catch { continue; }
  targets.push([name, 'installer copied to the project root']);
}
// Logs a test or build left in the project root.
for (const name of readdirSync(rootDir)) {
  if (name.endsWith('.log')) targets.push([name, 'log file']);
}

if (all) targets.push(['node_modules', 'installed dependencies']);

function sizeOf(path) {
  try {
    const st = statSync(path);
    if (!st.isDirectory()) return st.size;
    let total = 0;
    for (const entry of readdirSync(path, { withFileTypes: true })) {
      if (entry.isSymbolicLink()) continue;
      total += sizeOf(join(path, entry.name));
    }
    return total;
  } catch {
    return 0; // unreadable entries just do not count towards the total
  }
}

const mb = (bytes) => `${(bytes / 1024 / 1024).toFixed(1)} MB`;
let removed = 0;
let freed = 0;
let failed = 0;

for (const [rel, why] of targets) {
  const path = resolve(rootDir, rel);
  // Never step outside the project, whatever ends up in the list.
  if (path === rootDir || !path.startsWith(rootDir + sep)) continue;
  if (!existsSync(path)) continue;
  const bytes = sizeOf(path);
  const label = `${relative(rootDir, path).split(sep).join('/')}  (${why}, ${mb(bytes)})`;
  if (dryRun) {
    console.log(`[clean] would remove ${label}`);
    removed += 1;
    freed += bytes;
    continue;
  }
  try {
    rmSync(path, { recursive: true, force: true, maxRetries: 3, retryDelay: 200 });
    console.log(`[clean] removed ${label}`);
    removed += 1;
    freed += bytes;
  } catch (error) {
    // On Windows a running MyCapture (or an Explorer window) keeps files open.
    console.error(`[clean] could not remove ${label}: ${error.message}`);
    failed += 1;
  }
}

if (!removed && !failed) {
  console.log('[clean] Nothing to remove - already clean.');
} else {
  console.log(dryRun
    ? `[clean] ${removed} item(s), ${mb(freed)} would be removed. Run without --dry-run to delete.`
    : `[clean] ${removed} item(s) removed, ${mb(freed)} freed.`);
  if (!dryRun) {
    console.log(all
      ? '[clean] node_modules/ removed - run "npm install" before the next start, test or build.'
      : '[clean] node_modules/ kept - use "npm run clean:all" to remove it too.');
  }
}

if (failed) {
  console.error(`[clean] ${failed} item(s) could not be removed - close MyCapture (and Explorer windows on those folders) and retry.`);
  process.exit(1);
}
